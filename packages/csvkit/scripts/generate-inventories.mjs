import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

// Build-time discovery only. Product ESM has a closed, declarative import graph.
const root = fileURLToPath(new URL("../src/", import.meta.url));
const reference = JSON.parse(await readFile(new URL('../../../docs/csvkit/feature-register.json', import.meta.url), 'utf8'));
function settingType(action) {
  let value;
  if (action.action === '_AppendAction' && action.nargs === 2) value = 'readonly (readonly [string, unknown])[]';
  else if (action.action === '_AppendAction' || action.nargs === '*' || action.nargs === '+') value = 'readonly string[]';
  else if (action.action === '_StoreTrueAction' || action.action === '_StoreFalseAction') value = 'boolean';
  else if (action.choices) value = action.choices.map(choice => JSON.stringify(choice)).join(' | ');
  else if (action.type === 'builtins.int') value = 'number | bigint';
  else value = 'string';
  return action.default === null ? `${value} | null` : value;
}
const sdk = '// Generated from the frozen csvkit 2.2.0 flag inventory by scripts/generate-inventories.mjs.\n' +
  reference.commands.map(command => `export interface ${command.class}Settings {\n` +
    command.actions.filter(action => action.action !== '_HelpAction' && action.action !== '_VersionAction')
      .map(action => `  readonly ${action.dest}?: ${settingType(action)};\n`).join('') + '}\n').join('\n') +
  '\nexport interface CsvkitSettings {\n' + reference.commands.map(command => `  readonly ${command.name}: ${command.class}Settings;\n`).join('') +
  '}\nexport type CsvkitCommand = keyof CsvkitSettings;\n' +
  'export type CsvkitRequest = { [Name in CsvkitCommand]: { readonly command: Name; readonly settings?: CsvkitSettings[Name] } }[CsvkitCommand];\n';
const sdkDestination = path.join(root, 'sdk-settings.ts');
let previousSdk;
try { previousSdk = await readFile(sdkDestination, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (previousSdk !== sdk) await writeFile(sdkDestination, sdk);
for (const [family, type, typePath] of [
  ["commands", "CommandDescriptor", "./descriptor.js"],
  ["formats", "FormatDescriptor", "./formats/descriptor.js"],
  ["databases", "DatabaseDialectDescriptor", "./databases/descriptor.js"],
  ["sql-transports", "SqlTransportProfile", "./sql-transports/descriptor.js"],
]) {
  const files = (await readdir(path.join(root, family), { withFileTypes: true }))
    .filter(entry => entry.isFile() && entry.name.endsWith(".ts") && entry.name !== "descriptor.ts" && !entry.name.includes(".test."))
    .map(entry => entry.name.slice(0, -3)).sort();
  for (const name of files) {
    if (!name || [...name].some(char => !"abcdefghijklmnopqrstuvwxyz0123456789_".includes(char))) throw new Error(`Invalid ${family} descriptor filename`);
  }
  const text = "// Generated by scripts/generate-inventories.mjs; add one declarative descriptor file.\n" +
    `import type { ${type} } from "${typePath}";\n` +
    'import { freezeDescriptor } from "./descriptor.js";\n' +
    files.map(name => `import { ${name} } from "./${family}/${name}.js";\n`).join("") +
    `export const ${family === 'sql-transports' ? 'sqlTransportProfiles' : family}: readonly ${type}[] = Object.freeze([${files.join(", ")}].map(freezeDescriptor));\n`;
  const destination = path.join(root, `${family}.ts`);
  let existing;
  try { existing = await readFile(destination, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (existing !== text) await writeFile(destination, text);
}
