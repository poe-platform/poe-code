import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse, stringify } from "yaml";

const pkg = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const repoRoot = path.resolve(pkg, "../..");

const automations = [
  "fix-vulnerabilities",
  "github-issue-comment-created",
  "github-issue-opened",
  "github-pull-request-comment-created",
  "github-pull-request-opened",
  "github-pull-request-synchronized",
  "update-dependencies",
  "update-documentation"
] as const;

for (const name of automations) {
  const callerPath = path.join(pkg, "src/workflow-templates", `${name}.caller.yml`);
  const ejectedPath = path.join(pkg, "src/workflow-templates", `${name}.ejected.yml`);
  const outputPath = path.join(repoRoot, ".github/workflows", `gh-${name}.yml`);

  const caller = parse(readFileSync(callerPath, "utf8"));
  const ejected = parse(readFileSync(ejectedPath, "utf8"));

  // Build mapping: bare expression → inputs.NAME
  // e.g. "github.event.issue.number" → "inputs.ISSUE_NUMBER"
  const withBlock = (caller.jobs?.run?.with ?? {}) as Record<string, string>;
  const exprToInput = Object.fromEntries(
    Object.entries(withBlock).map(([inputName, wrappedExpr]) => {
      const bare = wrappedExpr.replace(/^\$\{\{\s*/, "").replace(/\s*\}\}$/, "");
      return [bare, `inputs.${inputName}`];
    })
  );

  const inputs = Object.fromEntries(
    Object.entries(withBlock).map(([inputName]) => [
      inputName,
      { required: true, type: inputName.endsWith("_NUMBER") ? "number" : "string" }
    ])
  );

  // Apply substitutions recursively through all string values
  const transformed = substituteAll(ejected, exprToInput);

  const output = {
    name: transformed.name,
    on: { workflow_call: { inputs } },
    ...(transformed.concurrency !== undefined ? { concurrency: transformed.concurrency } : {}),
    jobs: transformed.jobs
  };

  const content =
    `# Generated by: packages/github-workflows/scripts/generate-gh-workflows.ts\n` +
    `# Source: packages/github-workflows/src/workflow-templates/${name}.ejected.yml\n` +
    stringify(output, { lineWidth: 0 });

  writeFileSync(outputPath, content);
  console.log(`Generated ${path.relative(repoRoot, outputPath)}`);
}

function substituteAll(value: unknown, map: Record<string, string>): unknown {
  if (typeof value === "string") {
    let result = value;
    for (const [bare, replacement] of Object.entries(map)) {
      result = result.replaceAll(bare, replacement);
    }
    return result;
  }
  if (Array.isArray(value)) {
    return value.map((item) => substituteAll(item, map));
  }
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, substituteAll(v, map)])
    );
  }
  return value;
}
