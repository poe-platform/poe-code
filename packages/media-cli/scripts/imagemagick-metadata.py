"""ImageMagick advisory signed table and installed entrypoint identities.
No legacy grammar is inferred from the modern command table.
"""
import csv
import hashlib
import json
from pathlib import Path
import sys

package = Path(__file__).resolve().parent.parent
root = package.parent.parent
lock = json.loads((package / 'imagemagick-metadata-lock.json').read_text())
for name, digest in lock.items():
    if hashlib.sha256((root / name).read_bytes()).hexdigest() != digest:
        raise SystemExit('ImageMagick register drift: ' + name)
rows = csv.DictReader((package / 'metadata/option-tables.csv').open())
options = {r['name'].lower(): {'arity': int(r['arity']), 'flags': r['scope_flags'], 'source': r['path'] + ':' + r['line']}
           for r in rows if r['source_set'] == 'imagemagick-release' and r['table_kind'] == 'CommandOption'}
capabilities = json.loads((package / 'metadata/baselines/native-capabilities.json').read_text())
entries = capabilities['installed_imagemagick_entrypoints']
executables = {e['name']: {'path': str(Path(e['target']).parent / e['name']), 'sha256': e['sha256'],
                         'kind': 'build-helper' if e['name'].endswith('-config') else 'media'} for e in entries}
result = '// Generated by scripts/imagemagick-metadata.py. ImageMagick Studio LLC; see COPYING.ImageMagick and NOTICE.\n'
result += 'export const imageMagickOptions: Readonly<Record<string, { arity: number; flags: string; source: string }>> = ' + json.dumps(options, indent=2) + ';\n'
result += 'export const imageMagickGrammarRevision = "imagemagick-7.1.2-31-register-v1";\n'
result += 'export const imageMagickReference = ' + json.dumps({'id': lock['packages/media-cli/metadata/baselines/build-lock.json'], 'executables': executables}, indent=2) + ' as const;\n'
output = package / 'src/imagemagick.generated.ts'
if '--check' in sys.argv:
    if not output.exists() or output.read_text() != result:
        raise SystemExit('ImageMagick generated metadata drift')
else:
    output.write_text(result)
