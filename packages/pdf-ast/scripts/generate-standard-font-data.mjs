import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Reference revisions and licenses are recorded in THIRD_PARTY_NOTICES.md.
const [pdfjsDirectory, pdfiumDirectory] = process.argv.slice(2);
if (!pdfjsDirectory || !pdfiumDirectory) throw new Error("Usage: node generate-standard-font-data.mjs <PDF.js checkout> <directory containing PDFium FoxitSans*.cpp>");
const fonts = {
  Helvetica: "FoxitSans", "Helvetica-Bold": "FoxitSansBold", "Helvetica-Oblique": "FoxitSansItalic", "Helvetica-BoldOblique": "FoxitSansBoldItalic",
  "Times-Roman": "FoxitSerif", "Times-Bold": "FoxitSerifBold", "Times-Italic": "FoxitSerifItalic", "Times-BoldItalic": "FoxitSerifBoldItalic",
  Courier: "FoxitFixed", "Courier-Bold": "FoxitFixedBold", "Courier-Oblique": "FoxitFixedItalic", "Courier-BoldOblique": "FoxitFixedBoldItalic",
  Symbol: "FoxitSymbol", ZapfDingbats: "FoxitDingbats",
};
const encoded = {};
for (const [name, file] of Object.entries(fonts)) {
  let bytes;
  if (file.startsWith("FoxitSans")) {
    const source = readFileSync(resolve(pdfiumDirectory, file + ".cpp"), "utf8");
    const start = source.indexOf("{{"), end = source.indexOf("}}", start);
    if (start < 0 || end < 0) throw new Error(`Missing font byte array: ${file}`);
    const numbers = source.slice(start + 2, end).split(",").map(value => value.trim()).filter(Boolean).map(Number);
    if (numbers.some(value => !Number.isInteger(value) || value < 0 || value > 255)) throw new Error(`Invalid font bytes: ${file}`);
    bytes = Buffer.from(numbers);
  } else {
    bytes = readFileSync(resolve(pdfjsDirectory, "external/standard_fonts", file + ".pfb"));
  }
  encoded[name] = bytes.toString("base64");
}
writeFileSync(new URL("../src/fonts/standard-font-data.ts", import.meta.url),
  "// Generated by scripts/generate-standard-font-data.mjs. PDFium/Foxit BSD font data; see THIRD_PARTY_NOTICES.md.\n" +
  "export const STANDARD_FONT_CFF_BASE64 = " + JSON.stringify(encoded, null, 2) + " as const;\n");
