import { expect, it, vi } from "vitest";
import { createMemoryFileSystem } from "@poe-code/safe-fs";
import type { FileSystem } from "@poe-code/safe-fs/contracts";
import { PdfFileSource } from "../source.js";
import { parseContentEvents } from "./parser.js";
import { parseContentRangeEvents } from "./range-events.js";

async function fixture(text: string) {
  const bytes = new TextEncoder().encode(text);
  const reads = vi.fn(async (at: number, count: number) => bytes.slice(at, at + count));
  const fs = createMemoryFileSystem(); await fs.mkdir("/scratch");
  const input = { capabilities: { retainedRead: true }, openReadFile: async () => ({
    stat: async () => ({ type: "file", size: bytes.length }), read: reads, close: async () => {},
  }) } as unknown as FileSystem;
  const source = await PdfFileSource.open(input, "/input", { chunkBytes: 16, cacheBytes: 32 });
  return { bytes, source, reads, storage: { fs, directory: "/scratch" }, async close() {
    expect(await fs.readdir("/scratch")).toEqual([]); await source.close();
  } };
}

it.each([
  "q /Span << /MCID 7 /ActualText (label) >> BDC BT /F1 12 Tf (A) Tj (B) Tj ET EMC Q",
  "0 0 10 10 re W f BI /W 1 /H 1 /BPC 8 /CS /G ID a EI Q",
  "q BT /F1 12 Tf (A) Tj (B) Tj",
])("shares content event grammar through retained ranges: %s", async text => {
  const f = await fixture(text); const actual = [];
  try {
    for await (const event of parseContentRangeEvents(f.source, f.storage)) {
      if (event.kind === "inline-image" && !(event.data instanceof Uint8Array)) {
        expect(event.data.source).toBe(f.source);
        actual.push({ ...event, data: await event.data.source.read(event.data.start, event.data.end - event.data.start) });
      } else actual.push(event);
    }
    expect(actual).toEqual([...parseContentEvents(f.bytes)]);
  } finally { await f.close(); }
});

it.each([8192, 131072])("retains an inline image range for %i generated bytes without payload storage", async length => {
  const prefix = new TextEncoder().encode("BI /F /DCT ID "), suffix = new TextEncoder().encode(" EI Q");
  const size = prefix.length + length + suffix.length; let peak = 0, total = 0;
  const fs = { capabilities: { retainedRead: true }, openReadFile: async () => ({
    stat: async () => ({ type: "file", size }), close: async () => {},
    read: async (at: number, count: number) => {
      peak = Math.max(peak, count); total += count;
      const bytes = new Uint8Array(Math.min(count, size - at));
      for (let i = 0; i < bytes.length; i++) {
        const p = at + i; bytes[i] = p < prefix.length ? prefix[p]! : p < prefix.length + length ? 128 : suffix[p - prefix.length - length]!;
      }
      return bytes;
    },
  }) } as unknown as FileSystem;
  const source = await PdfFileSource.open(fs, "/input", { chunkBytes: 4096, cacheBytes: 4096 });
  const work = parseContentRangeEvents(source, { fs, directory: "/no-staging" });
  try {
    const event = (await work.next()).value;
    expect(event).toMatchObject({ kind: "inline-image", data: { kind: "range", start: prefix.length, end: prefix.length + length } });
    expect(peak).toBeLessThanOrEqual(4096);
    const before = total; await Promise.resolve(); expect(total).toBe(before);
  } finally { await work.return(); await source.close(); }
});

it.each([false, true])("cleans spilled operands on early stop, cancellation %s", async cancel => {
  const f = await fixture("/F q ".repeat(1000)); const controller = new AbortController();
  const work = parseContentRangeEvents(f.source, f.storage, { chunkBytes: 32, signal: controller.signal });
  try {
    for (let i = 0; i < 70; i++) await work.next();
    expect(await f.storage.fs.readdir("/scratch")).not.toEqual([]);
    expect(Math.max(...f.reads.mock.calls.map(([at]) => at))).toBeLessThan(512);
    const reads = f.reads.mock.calls.length; await Promise.resolve(); expect(f.reads.mock.calls.length).toBe(reads);
    if (cancel) { const failure = new Error("cancel content"); controller.abort(failure); await expect(work.next()).rejects.toBe(failure); }
    else await work.return();
    expect(await f.source.read(0, 1)).toEqual(new Uint8Array([47]));
  } finally { await work.return(); await f.close(); }
});


it("forwards borrowed inline-image ranges to the evaluator without another read", async () => {
  const { evaluateContentSteps } = await import("./evaluator.js");
  const f = await fixture("BI /W 1 /H 1 /BPC 8 /CS /G ID a EI");
  const events = parseContentRangeEvents(f.source, f.storage);
  const work = evaluateContentSteps({ pageIndex: 0, width: 10, height: 10 });
  try {
    const event = (await events.next()).value!;
    expect(event.kind).toBe("inline-image");
    const reads = f.reads.mock.calls.length;
    expect(work.next().value).toEqual({ kind: "node" });
    const request = work.next(event).value;
    expect(request).toMatchObject({ kind: "inline-image" });
    if (event.kind !== "inline-image" || !request || request.kind !== "inline-image") throw new Error("Expected inline image");
    expect(request.data).toBe(event.data);
    expect(f.reads.mock.calls.length).toBe(reads);
  } finally { work.return(); await events.return(); await f.close(); }
});
