function glyph(unicode: string, x: number, y: number, extra: Partial<PdfPlacedGlyph> = {}): PdfPlacedGlyph {
  return { unicode, charCode: 65, bbox: [x, y, x + 5, y + 10], baselineY: y, advanceWidth: 5, matrix: [1, 0, 0, 1, x, y], fontSize: 10, fontName: "Helvetica", color: { r: 0, g: 0, b: 0 }, ...extra };
}
const scenarios: PdfPlacedGlyph[][] = [
  [glyph("\ud83d", 0, 80), glyph("\ude00", 5, 80)],
  [], [glyph("hello", 0, 80), glyph("world", 30, 80)],
  [glyph("para-", 0, 80), glyph("graph", 0, 65), glyph("other", 0, 20)],
  [glyph("heading", 0, 100, { fontSize: 18 }), glyph("body", 0, 80), glyph("•", 0, 60), glyph("bullet", 20, 60)],
  [glyph(" ", 0, 80), glyph("\t", 10, 80), glyph("text", 20, 60)],
  [glyph("x", 0, 80, { actualText: "replacement", mcid: 1 }), glyph("y", 5, 80, { actualText: "replacement", mcid: 1 }), glyph("z", 10, 80)],
  [glyph("😀日本語", 0, 80), glyph("é", 5, 80), glyph("\u2003-", 0, 60), glyph("list", 20, 60)],
  [glyph(" ", 0, 80), glyph("right", 100, 80), glyph("left", -10, 80), glyph("next", -10, 65)],
  [glyph("diagonal", 0, 80, { matrix: [1, 1, -1, 1, 0, 80] }), glyph("clipped", 0, 40, { clipRect: [100, 100, 200, 200] }), glyph("ok", 0, 20)],
];
function expected(glyphs: PdfPlacedGlyph[], options: ExtractTextOptions) {
  const display: PdfDisplayList = { pageIndex: 0, width: 200, height: 200, rotation: 0, glyphs, paths: [], images: [], operations: [], annotations: [] };
  return formatExtractedPageText(extractPageFromDisplayList(display, { ...options, mode: "raw" }), { ...options, mode: "raw" });
}
it.each(scenarios.map((glyphs, index) => ({ glyphs, index })))("preserves buffered raw text for scenario $index", async ({ glyphs }) => {
  for (const options of [{}, { rejoinHyphens: false }, { discardDiagonal: true, clipText: true }]) {
    const fs = createMemoryFileSystem(); await fs.mkdir("/scratch"); let actual = ""; const decoder = new TextDecoder();
    for await (const chunk of streamRawTextChunks(glyphs, { fs, directory: "/scratch" }, { ...options, chunkBytes: 8 })) {
      expect(chunk.byteLength).toBeLessThanOrEqual(8); actual += decoder.decode(chunk, { stream: true }); await Promise.resolve();
    }
    actual += decoder.decode(); expect(actual).toBe(expected(glyphs, options)); expect(await fs.readdir("/scratch")).toEqual([]);
  }
});
it("cleans a staged line when the consumer returns or throws", async () => {
  const fs = createMemoryFileSystem(); await fs.mkdir("/scratch"); let closed = false;
  async function* input() { try { for (let i = 0; i < 1000; i++) yield glyph("a", i * 5, 80); } finally { closed = true; } }
  for (const reject of [false, true]) {
    closed = false; const work = streamRawTextChunks(input(), { fs, directory: "/scratch" }, { chunkBytes: 32 });
    await work.next();
    if (reject) { const error = { reason: "consumer" }; await expect(work.throw(error)).rejects.toBe(error); } else await work.return();
    expect(closed).toBe(true); expect(await fs.readdir("/scratch")).toEqual([]);
  }
});

it.each([8192, 131072])("formats %i generated bytes with fixed scratch and scalar external storage", async length => {
  const chunkBytes = 1024, scope = {}; let size = 0, revision = 0, live = false, pendingWrite = false, peak = 0, produced = 0, reads = 0;
  const stat = () => ({ type: "file" as const, size, revision, identityScope: scope, opaqueIdentity: "line" });
  const fs = {
    capabilities: { retainedRead: true, retainedStagingWrite: true, retainedStagingCleanup: true },
    stat: async () => ({ type: "directory", size: 0 }),
    async createStagedFile(path: string) {
      expect(live).toBe(false); live = true;
      return { file: { path, stat: stat() }, cleanup: { remove: async () => { live = false; }, close: async () => {} }, writer: {
        async write(bytes: Uint8Array) {
          expect(pendingWrite).toBe(false); pendingWrite = true; peak = Math.max(peak, bytes.buffer.byteLength);
          expect(bytes.every(byte => byte === 97)).toBe(true); await Promise.resolve(); size += bytes.length; revision++; pendingWrite = false;
        }, finish: async () => stat(),
      } };
    },
    async openReadFile() { return { stat: async () => stat(), close: async () => {}, async read(at: number, count: number) {
      reads++; expect(count).toBeLessThanOrEqual(chunkBytes); return new Uint8Array(Math.min(count, size - at)).fill(97);
    } }; },
    readFile() { throw new Error("whole read forbidden"); }, writeFile() { throw new Error("whole write forbidden"); },
  } as unknown as import("@poe-code/safe-fs/contracts").FileSystem;
  async function* glyphs() {
    for (let at = 0; at < length; at += 32) { expect(pendingWrite).toBe(false); produced += 32; yield glyph("a".repeat(32), at * 5, 80, { advanceWidth: 160 }); }
  }
  let total = 0, admitted = 0;
  const work = streamRawTextChunks(glyphs(), { fs, directory: "/external" }, { chunkBytes, onAllocation(bytes) { admitted += bytes; } });
  for await (const chunk of work) {
    expect(chunk.every(byte => byte === 97)).toBe(true); total += chunk.length;
    const before = reads; await Promise.resolve(); expect(reads).toBe(before);
  }
  expect(total).toBe(length); expect(produced).toBe(length); expect(size).toBe(length);
  expect(peak).toBeLessThanOrEqual(chunkBytes); expect(admitted).toBe(chunkBytes * 8 + 4096); expect(live).toBe(false);
});

it("does not share future output bytes with a previously yielded buffer", async () => {
  const fs = createMemoryFileSystem(); await fs.mkdir("/scratch");
  const work = streamRawTextChunks([glyph("abcdefghij", 0, 80)], { fs, directory: "/scratch" }, { chunkBytes: 8 });
  const first = (await work.next()).value!; const prefix = new TextDecoder().decode(first);
  new Uint8Array(first.buffer).fill(120);
  let rest = ""; for await (const chunk of work) rest += new TextDecoder().decode(chunk);
  expect(prefix + rest).toBe("abcdefghij"); expect(await fs.readdir("/scratch")).toEqual([]);
});

