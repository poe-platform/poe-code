export type MSO_AUTO_SHAPE_TYPE = (typeof values)[keyof typeof values];
export interface ShapePresetMetadata {
  readonly name: keyof typeof values;
  readonly value: MSO_AUTO_SHAPE_TYPE;
  readonly xml_value: string;
}
const entries = (Object.keys(values) as (keyof typeof values)[]).map((name) =>
  Object.freeze({ name, value: values[name], xml_value: shapePresets[name] })
);
function invalid(): never {
  throw new OfficeError("invalid-value", "Unknown shape preset.", "usage");
}
export const MSO_AUTO_SHAPE_TYPE = Object.freeze(
  Object.assign(values, {
    metadata(value: MSO_AUTO_SHAPE_TYPE): ShapePresetMetadata {
      return entries.find((entry) => entry.value === value) ?? invalid();
    },
    from_xml(xml_value: string): MSO_AUTO_SHAPE_TYPE {
      return entries.find((entry) => entry.xml_value === xml_value)?.value ?? invalid();
    },
    to_xml(value: MSO_AUTO_SHAPE_TYPE): string {
      return entries.find((entry) => entry.value === value)?.xml_value ?? invalid();
    },
    validate(value: MSO_AUTO_SHAPE_TYPE): void {
      if (!entries.some((entry) => entry.value === value)) invalid();
    }
  })
);
export { MSO_AUTO_SHAPE_TYPE as MSO_SHAPE };
