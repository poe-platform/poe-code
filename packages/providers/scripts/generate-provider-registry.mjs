import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const providersDirectory = path.join(packageDirectory, "src", "providers");
const generatedPath = path.join(providersDirectory, "generated.ts");

const fileNames = (await readdir(providersDirectory))
  .filter(isProviderSourceFile)
  .sort();

const providers = fileNames.map((fileName) => {
  const id = fileName.slice(0, -".ts".length);
  return {
    id,
    exportName: `${toCamelCase(id)}Provider`
  };
});

const content = [
  "// Generated by packages/providers/scripts/generate-provider-registry.mjs. Do not edit manually.",
  'import { orderAuthProviders } from "../provider-order.js";',
  ...providers.map(
    (provider) => `import { ${provider.exportName} } from "./${provider.id}.js";`
  ),
  "",
  ...providers.map((provider) => `export * from "./${provider.id}.js";`),
  "",
  "export const allAuthProviders = orderAuthProviders([",
  ...providers.map((provider, index) => {
    const suffix = index === providers.length - 1 ? "" : ",";
    return `  ${provider.exportName}${suffix}`;
  }),
  "]);",
  ""
].join("\n");

const existing = await readFile(generatedPath, "utf-8").catch((error) => {
  if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
    return "";
  }
  throw error;
});

if (existing !== content) {
  await writeFile(generatedPath, content);
}

function isProviderSourceFile(fileName) {
  return fileName.endsWith(".ts") &&
    !fileName.endsWith(".test.ts") &&
    fileName !== "generated.ts";
}

function toCamelCase(value) {
  let result = "";
  let capitalizeNext = false;
  for (const char of value) {
    if (char === "-" || char === "_") {
      capitalizeNext = true;
      continue;
    }
    if (result.length === 0) {
      result += char.toLowerCase();
      continue;
    }
    result += capitalizeNext ? char.toUpperCase() : char;
    capitalizeNext = false;
  }
  return result;
}
