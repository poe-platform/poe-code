export async function measureReplayGain(
  channels: MediaAudioData["channelData"], sampleRate: number,
  budget: MediaBudgetTracker, signal?: AbortSignal
): Promise<string> {
  const weights = coefficients[sampleRate];
  if (!weights) throw new Error(`replaygain: unsupported sample rate ${sampleRate}`);
  if (channels.length !== 2) throw new Error("replaygain: requires stereo audio");
  // Fixed memory: a 0.01 dB histogram and two small filter histories per channel.
  const histogram = new Uint32Array(12000);
  const states = channels.map(() => [10, 2].map(order => ({
    input: new Float32Array(order + 1), output: new Float32Array(order + 1), position: 0
  })));
  const windowSize = Math.floor(sampleRate / 20);
  const frames = channels[0]!.length;
  let peak = 0;
  let windows = 0;
  let work = 0;
  for (let start = 0; start < frames; start += windowSize) {
    const end = Math.min(frames, start + windowSize);
    let sum = 1e-16;
    for (const stages of states) for (const state of stages) {
      if (state.input.every(x => Math.abs(x) <= 1e-10) && state.output.every(x => Math.abs(x) <= 1e-10)) {
        state.input.fill(0);
        state.output.fill(0);
      }
    }
    for (let frame = start; frame < end; frame++) {
      if (++work % 1024 === 0) { budget.checkCpu(); await yieldTurn(signal); signal?.throwIfAborted(); }
      let power = 0;
      for (let channel = 0; channel < 2; channel++) {
        let value = Math.fround(channels[channel]![frame]!);
        peak = Math.max(peak, Math.abs(value));
        for (let stage = 0; stage < 2; stage++) {
          const state = states[channel]![stage]!;
          const b = weights[stage * 2]!;
          const a = weights[stage * 2 + 1]!;
          const size = state.input.length;
          const position = state.position;
          state.input[position] = value;
          let filtered = value * b[0]!;
          for (let lag = 1; lag < size; lag++) {
            const previous = (position + size - lag) % size;
            filtered += state.input[previous]! * b[lag]! - state.output[previous]! * a[lag]!;
          }
          value = Math.fround(filtered);
          state.output[position] = value;
          state.position = (position + 1) % size;
        }
        power = Math.fround(power + Math.fround(value * value));
      }
      sum += power;
    }
    const level = Math.floor(100 * (10 * Math.log10(sum / (end - start)) + 87));
    const bin = Math.max(0, Math.min(histogram.length - 1, level));
    histogram[bin] = histogram[bin]! + 1;
    windows++;
  }
  let loud = 0;
  let bin = histogram.length - 1;
  for (; bin >= 0; bin--) {
    loud += histogram[bin]!;
    if (loud * 20 >= windows) break;
  }
  const gain = Math.max(-24, Math.min(64, Math.fround(64.54 - bin / 100)));
  return `track_gain = ${gain >= 0 ? "+" : ""}${gain.toFixed(2)} dB\ntrack_peak = ${peak.toFixed(6)}\n`;
}
