const p2 = [
  -0.00022210262233306573,
  0.013067392038106924,
  -0.4470080572117445,
  5.567451837124076,
  -23.51794567923948,
  31.61132281870113,
  -9.609002196865617,
];
const q2 = [
  -0.0005519433023100548,
  0.03254769759481962,
  -1.1151759188741313,
  13.982595353892851,
  -60.22800206674334,
  85.53956325801293,
  -31.44669027513549,
  1.0,
];
function polynomial(coefficients: readonly number[], x: number): number {
  let value = coefficients[coefficients.length - 1]!;
  for (let i = coefficients.length - 2; i >= 0; i--) value = value * x + coefficients[i]!;
  return value;
}

export function besselI0(x: number): number {
  if (x === 0) return 1;
  x = Math.abs(x);
  if (x <= 15) return polynomial(p1, x * x) / polynomial(q1, x * x);
  const y = 1 / x - 1 / 15;
  return (Math.exp(x) / Math.sqrt(x)) * (polynomial(p2, y) / polynomial(q2, y));
}
