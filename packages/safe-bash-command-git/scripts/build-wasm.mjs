import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const root=new URL('../',import.meta.url);
execFileSync('rustup',['target','add','wasm32-unknown-unknown'],{stdio:'inherit'});
execFileSync('cargo',['build','--manifest-path',new URL('../git-rust/Cargo.toml',root).pathname,'--target','wasm32-unknown-unknown','--target-dir',new URL('../git-rust/target',root).pathname,'--release','--locked'],{stdio:'inherit'});
const bytes=readFileSync(new URL('../git-rust/target/wasm32-unknown-unknown/release/git_rust.wasm',root));
writeFileSync(new URL('src/wasm.generated.ts',root),`// Generated by scripts/build-wasm.mjs.\nexport function wasmBytes(): Uint8Array { return Uint8Array.from(atob('${bytes.toString('base64')}'), c=>c.charCodeAt(0)); }\n`);
writeFileSync(new URL('dist/git_rust.wasm',root),bytes);
