import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import { resolveCargoTargetDirectory } from "../../mcp-protocol-rust/scripts/cargo-target.mjs";
import process from "node:process";
const root = new URL("../", import.meta.url);
const targetRoot = pathToFileURL(resolveCargoTargetDirectory(fileURLToPath(new URL("../../", root))) + path.sep);
const env = typeof process !== "undefined" && process.env ? { ...process.env, PATH: `${process.env.CARGO_HOME ? `${process.env.CARGO_HOME}/bin` : `${process.env.HOME ?? ""}/.cargo/bin`}:${os.homedir()}/.cargo/bin:${process.env.PATH ?? ""}` } : undefined;
const installed = execFileSync("rustup", ["target", "list", "--installed", "--toolchain", "stable"], { encoding: "utf8", env }).split(/\r?\n/);
if (!installed.includes("wasm32-unknown-unknown")) {
  execFileSync("rustup", ["target", "add", "wasm32-unknown-unknown", "--toolchain", "stable"], { stdio: "inherit", env });
}
execFileSync("rustup", ["run", "stable", "cargo", "build", "--manifest-path", new URL("../git-rust/Cargo.toml", root).pathname, "--target", "wasm32-unknown-unknown", "--target-dir", new URL(".", targetRoot).pathname.replace(/\/$/, ""), "--release", "--locked"], { stdio: "inherit", env });
const bytes = readFileSync(new URL("wasm32-unknown-unknown/release/git_rust.wasm", targetRoot));
writeFileSync(new URL("src/wasm.generated.ts", root), `// Generated by scripts/build-wasm.mjs.\nexport function wasmBytes(): Uint8Array { const binary = atob('${bytes.toString("base64")}'); const bytes = new Uint8Array(binary.length); for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i); return bytes; }\n`);
mkdirSync(new URL("dist/", root), { recursive: true });
writeFileSync(new URL("dist/git_rust.wasm", root), bytes);
