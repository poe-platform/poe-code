for (const mode of ["buffered", "retained", "sync"] as const) {
    it.each([...Object.keys(nativeRows), "reset"])(`honors Canny channel selection via ${mode}: %s`, async channel => {
        const width = 32, height = 24, data = new Uint8Array(width * height * 4);
        for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
            const edge = y === 5 && x >= 2 && x <= 29
                || (y === 10 || y === 19) && x >= 8 && x <= 21
                || (x === 8 || x === 21) && y >= 10 && y <= 19;
            data.set(edge ? [0, 255, 0, 255] : [255, 0, 0, 255], (y * width + x) * 4);
        }
        const input = encodeImage({ width, height, data, format: "png", density: 72,
            channels: 3, hasAlpha: false, space: "srgb", depth: "uchar" }, { format: "png" }).data;
        const files = new Map([["input.png", input]]), filesystem = new MemoryFileSystem();
        await filesystem.writeFile("/input.png", input);
        const args = ["input.png", "-channel", channel === "reset" ? "R" : channel,
            ...(channel === "reset" ? ["+channel"] : []), "-canny", "0x1+10%+30%", "+channel", "out.png"];
        const result = mode === "sync" ? runConvertCliSync(args, files)
            : await runConvertCli(args, mode === "retained" ? { filesystem, cwd: "/" } : files);
        expect(result).toMatchObject({ exitCode: 0 });
        const output = decodeImage(mode === "retained" ? await filesystem.readFile("/out.png") : files.get("out.png")!).data;
        const rows = nativeRows[channel === "reset" ? "RGB" : channel as keyof typeof nativeRows];
        expect([...output]).toEqual([...rows.join("")].flatMap(bit => [Number(bit) * 255, Number(bit) * 255, Number(bit) * 255, 255]));
    });
}
