import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import { MemoryFileSystem } from "@poe-code/safe-fs/core";
import { runConvertCli, runConvertCliSync } from "./index.js";

const bytes = readFileSync(new URL("./fixtures/component-stripes.png", import.meta.url));
const rows = ["2x1+0+0 0.5,0.0 2 srgb(255,0,0)", "2x1+3+0 3.5,0.0 2 srgb(0,128,0)", "1x1+2+0 2.0,0.0 1 srgb(0,0,255)"];
for (const mode of ["buffered", "retained", "sync"] as const) {
 for (const [size, color, merge, row] of [
  ["2x1", "#ff000080", false, "2x1+0+0 0.5,0.0 2 srgba(255,0,0,32768)"],
  ["3x1", "#ff000080", false, "3x1+0+0 1.0,0.0 3 srgba(255,0,0,21845.5)"],
  ["1x1", "#ff000000", false, "1x1+0+0 0.0,0.0 1 srgba(255,0,0,65535)"],
  ["1x1", "#ff000080", true, "3x1+0+0 1.0,0.0 3 srgba(255,0,0,65535.5)"],
 ] as const) it(`reports native alpha for area and merging (${mode}, ${size}, ${color}, ${merge})`, async () => {
  const files = new Map<string, Uint8Array>(), fs = new MemoryFileSystem();
  const args = ["-size", size, `xc:${color}`, ...(merge ? ["xc:#ff0000ff", "xc:#ff000080", "+append", "-define", "connected-components:area-threshold=2"] : []), "-define", "connected-components:verbose=true", "-connected-components", "4", "out.png"];
  const result = mode === "sync" ? runConvertCliSync(args, files) : await runConvertCli(args, mode === "buffered" ? files : { filesystem: fs, cwd: "/" });
  expect(result).toEqual({ exitCode: 0, stderr: "", stdout: `Objects (id: bounding-box centroid area mean-color):\n  0: ${row}\n` });
 });
 it(`matches native Q16-HDRI RGBA component reports (${mode})`, async () => {
  // Generated by ImageMagick 7.1.2-31: three red pixels with alpha 128, 255, 128.
  const input = readFileSync(new URL("./fixtures/component-alpha.png", import.meta.url));
  const files = new Map([["input.png", input]]), fs = new MemoryFileSystem();
  await fs.writeFile("/input.png", input);
  const args = ["input.png", "-define", "connected-components:verbose=true", "-connected-components", "4", "out.png"];
  const result = mode === "sync" ? runConvertCliSync(args, files) : await runConvertCli(args, mode === "buffered" ? files : { filesystem: fs, cwd: "/" });
  expect(result).toEqual({ exitCode: 0, stderr: "", stdout: "Objects (id: bounding-box centroid area mean-color):\n  0: 1x1+0+0 0.0,0.0 1 srgba(255,0,0,65535.5)\n  1: 1x1+1+0 1.0,0.0 1 srgba(255,0,0,65536)\n  2: 1x1+2+0 2.0,0.0 1 srgba(255,0,0,65535.5)\n" });
 });
 for (const excludeHeader of [false, true]) for (const excludeIds of [false, true]) for (const reset of [false, true]) {
  it(`formats component reports (${mode}, header=${excludeHeader}, ids=${excludeIds}, reset=${reset})`, async () => {
   const files = new Map([["input.png", bytes]]), fs = new MemoryFileSystem();
   await fs.writeFile("/input.png", bytes);
   const args = ["input.png", "-define", `connected-components:exclude-header=${excludeHeader}`, "-define", `connected-components:exclude-ids=${excludeIds}`, ...(reset ? ["+define", "connected-components:exclude-header", "+define", "connected-components:exclude-ids"] : []), "-define", "connected-components:verbose=true", "-connected-components", "4", "out.png"];
   const result = mode === "sync" ? runConvertCliSync(args, files) : await runConvertCli(args, mode === "buffered" ? files : { filesystem: fs, cwd: "/" });
   const ids = excludeIds && !reset, header = excludeHeader && !reset ? "" : `Objects (${ids ? "" : "id: "}bounding-box centroid area mean-color):\n`;
   expect(result).toEqual({ exitCode: 0, stderr: "", stdout: header + rows.map((row, i) => `  ${ids ? "" : `${[0, 2, 1][i]}: `}${row}\n`).join("") });
   expect((mode === "retained" ? await fs.readFile("/out.png") : files.get("out.png"))?.length).toBeGreaterThan(0);
  });
 }
}
