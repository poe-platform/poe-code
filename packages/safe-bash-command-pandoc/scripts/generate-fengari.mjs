import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { portableLuaLibraries } from "./portable-lua.mjs";
import { asyncLuaParser } from "./async-lua-parser.mjs";

const require = createRequire(import.meta.url);
const directory = new URL("../src/", import.meta.url);
const license = await readFile(require.resolve("fengari/LICENSE"), "utf8");
// Use only the VM and libraries admitted by our filter capability. The upstream
// table/string libraries require lualib for its assertion helper alone.
const result = await build({
  stdin: { contents: `
    import {loadStream} from "./scripts/fengari-stream.mjs";
    import lua from "fengari/src/lua.js";
    import lauxlib from "fengari/src/lauxlib.js";
    import core from "fengari/src/fengaricore.js";
    import base from "fengari/src/lbaselib.js";
    import string from "fengari/src/lstrlib.js";
    import table from "fengari/src/ltablib.js";
    import math from "fengari/src/lmathlib.js";
    import utf8 from "fengari/src/lutf8lib.js";
    export default { lua, lauxlib, loadStream, to_luastring: core.to_luastring, to_jsstring: core.to_jsstring,
      lualib: { ...base, ...string, ...table, ...math, ...utf8 } };
  `, resolveDir: new URL("../", import.meta.url).pathname },
  bundle: true, platform: "browser", target: "es2022", format: "esm", write: false,
  define: { "process.env.FENGARICONF": "undefined", process: "undefined" },
  minify: true, legalComments: "inline",
  plugins: [asyncLuaParser, portableLuaLibraries],
});
await writeFile(new URL("fengari.generated.ts", directory),
  "/* eslint-disable */\n// @ts-nocheck\n// Generated by scripts/generate-fengari.mjs from fengari 0.1.5.\n/*!\n" + license + "*/\n" + result.outputFiles[0].text);
