import {build} from "esbuild";
import {createRequire} from "node:module";
import {readFile,writeFile} from "node:fs/promises";
import {compileLuaLibrary} from "./lua-library.mjs";

const license=await readFile(createRequire(import.meta.url).resolve("fengari/LICENSE"),"utf8");
const result=await build({entryPoints:[new URL("../src/lua-string-source.ts",import.meta.url).pathname],bundle:true,format:"esm",write:false});
const {luaStringSource}=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`);
await writeFile(new URL("../src/lua-string.generated.ts",import.meta.url),
  '/*!\n'+license+'*/\n'+
  '// Generated by scripts/generate-lua-string.mjs. Edit lua-string-source.ts.\n'+
  'import type {LuaLibraryPrototype} from "./lua-library.js";\n'+
  'export const stringLibrary: LuaLibraryPrototype = '+JSON.stringify(compileLuaLibrary(luaStringSource))+';\n');
