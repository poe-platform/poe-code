import {build} from "esbuild";
import {createRequire} from "node:module";
import {readFile,writeFile} from "node:fs/promises";
import {compileLuaLibrary} from "./lua-library.mjs";

const license=await readFile(createRequire(import.meta.url).resolve("fengari/LICENSE"),"utf8");
const result=await build({entryPoints:[new URL("../src/lua-table-source.ts",import.meta.url).pathname],bundle:true,format:"esm",write:false});
const {luaTableSource}=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`);
await writeFile(new URL("../src/lua-table.generated.ts",import.meta.url),
  '/*!\n'+license+'*/\n'+
  '// Generated by scripts/generate-lua-table.mjs. Edit lua-table-source.ts.\n'+
  'import type {LuaLibraryPrototype} from "./lua-library.js";\n'+
  'export const tableLibrary: LuaLibraryPrototype = '+JSON.stringify(compileLuaLibrary(luaTableSource))+';\n');
