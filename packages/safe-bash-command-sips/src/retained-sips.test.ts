import {expect,it} from "vitest";
import sharp,{decodeImage} from "@poe-code/image-ast";
import {MemoryFileSystem} from "@poe-code/safe-fs/core";
import {createCommandArguments,type CommandContext} from "safe-bash-contracts/command";
import {createSipsCommand,runSipsCli} from "./index.js";
import {writeProperties} from "./properties.js";

for(const format of ["png","jpeg","webp","gif","tiff","bmp","ppm"] as const)
for(const args of [["-g","all"],["-g","allxml"],["-g","description"],["-v"]])
it(`queries ${format} ${args.join(" ")} through retained caller input`,async()=>{
 let bytes=await sharp({create:{width:13,height:7,channels:4,background:"blue"}}).toFormat(format).toBuffer();
 if(format==="png"||format==="jpeg")bytes=writeProperties(bytes,format,new Map([["description","owned input"]]));
 const fs=new MemoryFileSystem();await fs.writeFile("/in",bytes);
 const filesystem=new Proxy(fs,{get(target,key){if(key==="readFile")return ()=>{throw new Error("whole input forbidden");};const value=Reflect.get(target,key,target);return typeof value==="function"?value.bind(target):value;}});
 const argv=[...args,"in"],expected=await runSipsCli(argv,new Map([["in",bytes]]));
 expect(await runSipsCli(argv,{filesystem,cwd:"/"})).toEqual(expected);
 const arguments_=createCommandArguments(argv),output:string[]=[],errors:string[]=[];
 const context={command:"sips",args:arguments_.args,argumentValues:arguments_,cwd:"/",env:{},fs:filesystem,signal:new AbortController().signal,stdin:(async function*(){})(),stdout:{async write(bytes:Uint8Array){output.push(new TextDecoder().decode(bytes));}},stderr:{async write(bytes:Uint8Array){errors.push(new TextDecoder().decode(bytes));}}} as CommandContext;
 expect({...await createSipsCommand().execute(context),stdout:output.join(""),stderr:errors.join("")}).toEqual(expected);
});

it("preserves mutation output through the same filesystem SDK",async()=>{
 const fs=new MemoryFileSystem();await fs.mkdir("/dir");const bytes=await sharp({create:{width:5,height:3,channels:3,background:"red"}}).png().toBuffer();await fs.writeFile("/in",bytes);
 const files=new Map([["in",bytes]]),args=["-r","90","in","-o","dir/"];
 expect(await runSipsCli(args,{filesystem:fs,cwd:"/"})).toEqual(await runSipsCli(args,files));
 expect(decodeImage(await fs.readFile("/dir/in"))).toEqual(decodeImage(files.get("dir/in")!));
});

it("retains intermediate writes when the same file is mutated twice",async()=>{
 const bytes=await sharp({create:{width:5,height:3,channels:3,background:"red"}}).png().toBuffer(),fs=new MemoryFileSystem();await fs.writeFile("/in",bytes);
 const files=new Map([["in",bytes]]),args=["-r","90","in","in"];
 expect(await runSipsCli(args,{filesystem:fs,cwd:"/"})).toEqual(await runSipsCli(args,files));
 expect(decodeImage(await fs.readFile("/in"))).toEqual(decodeImage(files.get("in")!));
});

it("checks file admission before payload reads and closes rejected sources",async()=>{
 const fs=new MemoryFileSystem(),bytes=await sharp({create:{width:3,height:2,channels:3,background:"red"}}).png().toBuffer();await fs.writeFile("/in",bytes);
 let reads=0,closed=0;const failure=new Error("admission"),open=fs.openReadFile!.bind(fs);
 const filesystem=new Proxy(fs,{get(target,key){if(key==="openReadFile")return async(...args:Parameters<typeof open>)=>{const handle=await open(...args);return {...handle,stat:handle.stat.bind(handle),async read(...args:Parameters<typeof handle.read>){reads++;return handle.read(...args);},async close(){closed++;await handle.close();}};};const value=Reflect.get(target,key,target);return typeof value==="function"?value.bind(target):value;}});
 await expect(runSipsCli(["-g","all","in"],{filesystem,cwd:"/",inputBudget:{check(){throw failure;}}})).rejects.toBe(failure);
 expect(reads).toBe(0);expect(closed).toBe(1);
});

it("propagates cancellation before help or file access",async()=>{
 const controller=new AbortController(),reason=new Error("cancel Sips");controller.abort(reason);
 await expect(runSipsCli(["--help"],{filesystem:new MemoryFileSystem(),cwd:"/"},controller.signal)).rejects.toBe(reason);
});

it("allows a later operand to consume output generated by an earlier operand",async()=>{
 const bytes=await sharp({create:{width:5,height:3,channels:3,background:"red"}}).png().toBuffer(),fs=new MemoryFileSystem();await fs.writeFile("/in",bytes);
 await fs.mkdir("/dir");
 const files=new Map([["in",bytes]]),args=["-r","90","in","dir/in","-o","dir/"];
 expect(await runSipsCli(args,{filesystem:fs,cwd:"/"})).toEqual(await runSipsCli(args,files));
 expect(decodeImage(await fs.readFile("/dir/in"))).toEqual(decodeImage(files.get("dir/in")!));
});
