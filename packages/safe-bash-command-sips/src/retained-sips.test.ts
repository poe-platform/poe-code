it("admits one retained mutation source before reads and closes it on rejection",async()=>{
 const fs=new MemoryFileSystem(),bytes=await sharp({create:{width:3,height:2,channels:3,background:"red"}}).png().toBuffer();await fs.writeFile("/in",bytes);
 const open=fs.openReadFile!.bind(fs);let opened=0,closed=0,reads=0;
 const filesystem=new Proxy(fs,{get(target,key){if(key==="openReadFile")return async(...args:Parameters<typeof open>)=>{opened++;const handle=await open(...args);return {...handle,stat:handle.stat.bind(handle),async read(...args:Parameters<typeof handle.read>){reads++;return handle.read(...args);},async close(){closed++;await handle.close();}};};const value=Reflect.get(target,key,target);return typeof value==="function"?value.bind(target):value;}});
 const failure=new Error("mutation admission");
 await expect(runSipsCli(["-r","90","in"],{filesystem,cwd:"/",inputBudget:{check(){throw failure;}}})).rejects.toBe(failure);
 expect({opened,closed,reads}).toEqual({opened:1,closed:1,reads:0});expect(await fs.readFile("/in")).toEqual(bytes);
});

for(const terminal of ["read","close"] as const)
it(`preserves mutation source ${terminal} failure identity`,async()=>{
 const fs=new MemoryFileSystem(),bytes=await sharp({create:{width:3,height:2,channels:3,background:"red"}}).png().toBuffer();await fs.writeFile("/in",bytes);
 const open=fs.openReadFile!.bind(fs),failure=new Error(`source ${terminal}`);let closed=0;
 const filesystem=new Proxy(fs,{get(target,key){if(key==="openReadFile")return async(...args:Parameters<typeof open>)=>{const handle=await open(...args);return {...handle,stat:handle.stat.bind(handle),async read(...args:Parameters<typeof handle.read>){if(terminal==="read")throw failure;return handle.read(...args);},async close(){closed++;await handle.close();if(terminal==="close")throw failure;}};};const value=Reflect.get(target,key,target);return typeof value==="function"?value.bind(target):value;}});
 await expect(runSipsCli(["-r","90","in"],{filesystem,cwd:"/"})).rejects.toBe(failure);
 expect(closed).toBe(1);expect(await fs.readFile("/in")).toEqual(bytes);
});

it("uses retained capabilities advertised for a mounted path",async()=>{
 const fs=new MemoryFileSystem(),bytes=await sharp({create:{width:5,height:3,channels:3,background:"red"}}).png().toBuffer();await fs.writeFile("/in",bytes);
 const filesystem=new Proxy(fs,{get(target,key){if(key==="capabilities")return {...fs.capabilities,retainedRead:false};if(key==="capabilitiesFor")return async()=>fs.capabilities;if(key==="readFile"||key==="writeFile")return ()=>{throw new Error("whole I/O forbidden");};const value=Reflect.get(target,key,target);return typeof value==="function"?value.bind(target):value;}});
 expect((await runSipsCli(["-r","90","in"],{filesystem,cwd:"/"})).exitCode).toBe(0);
 expect(await sharp(await fs.readFile("/in")).metadata()).toMatchObject({width:3,height:5});
});
