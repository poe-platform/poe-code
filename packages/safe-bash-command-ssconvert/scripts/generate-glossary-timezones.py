"""Extract pinned TZif transitions; never consult the host timezone at runtime.

Usage: python3 scripts/generate-glossary-timezones.py /usr/share/zoneinfo
The source files are tzdb 2026b as distributed by macOS (public-domain tz data).
SHA256 guards ensure that updating a source is an intentional profile change.
"""
import hashlib
import json
from pathlib import Path
import struct
import sys

SOURCES = {
    "UTC": "8b85846791ab2c8a5463c83a5be3c043e2570d7448434d41398969ed47e3e6f2",
    "America/Los_Angeles": "68977bb9ad6d186fefc6c7abd36010a66e30008dcb2d376087a41c49861e7268",
    "Asia/Kolkata": "e90c341036cb7203200e293cb3b513267e104a39a594f35e195254e6bc0a17cf",
    "Europe/Warsaw": "4e22c33db79517472480b54491a49e0da299f3072d7490ce97f1c4fd6779acab",
}
START = 0
END = 2145916800  # 2038-01-01 UTC, before the 32-bit TZif horizon


def transitions(data):
    # TZif's first block is the 32-bit profile, enough for the admitted range.
    isgmt, isstd, leap, count, types, chars = struct.unpack(">6I", data[20:44])
    if data[:4] != b"TZif":
        raise ValueError("Not TZif")
    times = struct.unpack(f">{count}i", data[44:44 + count * 4])
    indexes = data[44 + count * 4:44 + count * 5]
    at = 44 + count * 5
    records = [struct.unpack(">iBB", data[at + i * 6:at + (i + 1) * 6]) for i in range(types)]
    names = data[at + types * 6:at + types * 6 + chars]
    def value(index):
        offset, _dst, name = records[index]
        return [offset, names[name:names.index(b"\0", name)].decode("ascii")]
    current = value(0)
    rows = []
    for time, index in zip(times, indexes):
        if time <= START:
            current = value(index)
        elif time < END:
            rows.append([time, *value(index)])
    return [[START, *current], *rows]


root = Path(sys.argv[1])
lines = ["// Generated by scripts/generate-glossary-timezones.py from pinned tzdb 2026b TZif.",
         "// Public-domain timezone facts; see glossary-timezones-NOTICE.md.",
         "export const glossaryTimezoneEnd = 2145916800000; // 2038-01-01 UTC (exclusive)",
         "export const glossaryTimezones: Readonly<Record<string, readonly (readonly [number, number, string])[]>> = {"]
for zone, digest in SOURCES.items():
    data = (root / zone).read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"Source hash mismatch: {zone}")
    lines.append(f"  {json.dumps(zone)}: [")
    lines.extend(f"    {json.dumps(row)}," for row in transitions(data))
    lines.append("  ],")
lines.append("};")
(Path(__file__).resolve().parent.parent / "src/codecs/glossary-timezones.ts").write_text("\n".join(lines) + "\n")
