it("observes cancellation between fixed numerical stages", () => {
  const stop = new Error("cancelled"); let ticks = 0;
  expect(() => capturedPow(.756300583193119, 4, { tick() { if (++ticks === 3) throw stop; } })).toThrow(stop);
  expect(ticks).toBe(3);
});
