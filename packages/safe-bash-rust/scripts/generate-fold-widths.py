"""Generate fold widths from Unicode's Public/{17.0.0,14.0.0}/ucd directories.

Usage: python generate-fold-widths.py <ucd-17-directory> <ucd-14-directory>
"""
from hashlib import sha256
from itertools import groupby
from pathlib import Path
import sys

ucd17, ucd14 = map(Path, sys.argv[1:])
sources = {
    ucd17 / "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    ucd17 / "PropList.txt": "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
    ucd17 / "HangulSyllableType.txt": "5a57450afde0d082bc5026f7458649eac3b615490cc7e3d916b0367f1593c0e3",
    ucd14 / "EastAsianWidth.txt": "f901ac011aa32a09224d6555da71e2532c59c1d3381322829de0e3b880507250",
}
for path, digest in sources.items():
    if sha256(path.read_bytes()).hexdigest() != digest:
        sys.exit(f"Unexpected Unicode data: {path}")


def properties(path):
    for line in path.read_text().splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            bounds, name = map(str.strip, data.split(";"))
            ends = [int(v, 16) for v in bounds.split("..")]
            yield range(ends[0], ends[-1] + 1), name


zero = set()
for line in (ucd17 / "UnicodeData.txt").read_text().splitlines():
    code, _, category, _, bidi, *_ = line.split(";")
    if category in ("Cf", "Cc") or bidi == "NSM":
        zero.add(int(code, 16))
for points, prop in properties(ucd17 / "PropList.txt"):
    if prop == "Prepended_Concatenation_Mark":
        zero.difference_update(points)
for points, prop in properties(ucd17 / "HangulSyllableType.txt"):
    if prop in ("V", "T"):
        zero.update(points)
# fold counts nonprinting controls as one cell; NUL is handled by its input path.
zero.difference_update(range(1, 160))

wide, listed = set(), set()
for points, prop in properties(ucd14 / "EastAsianWidth.txt"):
    listed.update(points)
    if prop in ("W", "F"):
        wide.update(points)
# The command also assigns wide cells to reserved positions within these CJK,
# presentation-form and ideographic ranges, including the ends of planes 2/3.
for start, end in [(0x2E80, 0xA4CF), (0xFE10, 0xFE1F), (0xFE30, 0xFE6F),
                   (0xFF00, 0xFF60), (0x1F200, 0x1F2FF), (0x20000, 0x3FFFF)]:
    wide.update(set(range(start, end + 1)) - listed)

output = "// Generated by scripts/generate-fold-widths.py from Unicode data. See LICENSE.UNICODE.\n"
for name, points in [("ZERO", zero), ("WIDE", wide - zero)]:
    output += f"pub(super) const {name}: &[(u32, u32)] = &[\n"
    for _, group in groupby(enumerate(sorted(points)), lambda pair: pair[1] - pair[0]):
        run = [value for _, value in group]
        output += f"    (0x{run[0]:x}, 0x{run[-1]:x}),\n"
    output += "];\n"
(Path(__file__).resolve().parents[1] / "src/commands/coreutils/fold_widths.rs").write_text(output)
