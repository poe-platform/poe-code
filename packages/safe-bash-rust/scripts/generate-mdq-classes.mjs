import { writeFileSync } from "node:fs";

if (process.versions.unicode !== "16.0") throw new Error("Use Node with Unicode 16.0");
let source = "// Unicode 16.0; see LICENSE.UNICODE. Generated by scripts/generate-mdq-classes.mjs.\n";
for (const [name, pattern] of [
  ["WORD", /^[\p{Alphabetic}\p{M}\p{Nd}\p{Pc}\p{Join_Control}]$/u],
  ["DIGIT", /^\p{Nd}$/u], ["SPACE", /^\p{White_Space}$/u], ["HEX", /^[a-fA-F0-9]$/u],
]) {
  const edges = [];
  let inside = false;
  for (let i = 0; i <= 0x10ffff; i++) {
    const next = pattern.test(String.fromCodePoint(i));
    if (next !== inside) edges.push("0x" + i.toString(16));
    inside = next;
  }
  if (inside) edges.push("0x110000");
  source += "#[rustfmt::skip]\npub(super) const " + name + ": &[u32] = &[\n";
  for (let i = 0; i < edges.length; i += 12) source += "    " + edges.slice(i, i + 12).join(", ") + ",\n";
  source += "];\n";
}
writeFileSync(new URL("../src/commands/search/mdq_classes.rs", import.meta.url), source);
