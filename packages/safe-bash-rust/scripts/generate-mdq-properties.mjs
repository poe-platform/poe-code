import { readFileSync, writeFileSync } from "node:fs";

// Supply PropertyAliases.txt and PropertyValueAliases.txt from https://www.unicode.org/Public/16.0.0/ucd/.
if (process.versions.unicode !== "16.0") throw new Error("Use Node with Unicode 16.0");
function rows(path, name) {
  const text = readFileSync(path, "utf8");
  if (!text.startsWith("# " + name + "-16.0.0.txt")) throw new Error("Expected Unicode 16.0.0 " + name);
  return text.split("\n").map(line => line.split("#")[0].trim()).filter(Boolean)
    .map(line => line.split(";").map(alias => alias.trim()));
}
const aliases = new Set(["ASCII", "Any", "Assigned"]);
for (const row of rows(process.argv[2], "PropertyAliases")) for (const alias of row) aliases.add(alias);
for (const [key, ...values] of rows(process.argv[3], "PropertyValueAliases")) {
  for (const value of values) {
    if (key === "gc") {
      aliases.add(value);
      aliases.add("General_Category=" + value);
    } else if (key === "sc") {
      aliases.add("Script=" + value);
      aliases.add("Script_Extensions=" + value);
    }
  }
}

let scalars = "";
for (let i = 0; i < 0x110000; i++) if (i < 0xd800 || i > 0xdfff) scalars += String.fromCodePoint(i);
const bytes = [], offsets = [0], tableIds = new Map(), names = [];
function table(pattern) {
  const edges = [];
  for (const [run] of scalars.matchAll(pattern)) {
    const last = run.length - 1, low = run.charCodeAt(last);
    edges.push(run.codePointAt(0), 1 + run.codePointAt(low >= 0xdc00 && low <= 0xdfff ? last - 1 : last));
  }
  const key = edges.join(","), known = tableIds.get(key);
  if (known !== undefined) return known;
  const id = tableIds.size;
  tableIds.set(key, id);
  let previous = 0;
  for (const edge of edges) {
    let delta = edge - previous; previous = edge;
    while (delta >= 128) { bytes.push((delta & 127) | 128); delta >>>= 7; }
    bytes.push(delta);
  }
  offsets.push(bytes.length);
  return id;
}
for (const name of [...aliases].sort()) {
  let pattern;
  try { pattern = new RegExp("\\p{" + name + "}+", "gu"); } catch { continue; }
  names.push("    (" + JSON.stringify(name) + ", " + table(pattern) + ", " +
    table(new RegExp(pattern.source, "giu")) + "),");
}
const src = "// Unicode 16.0; see LICENSE.UNICODE. Generated by scripts/generate-mdq-properties.mjs.\n" +
  "#[rustfmt::skip]\npub(super) const OFFSETS: &[usize] = &[\n" +
  Array.from({ length: Math.ceil(offsets.length / 12) }, (_, i) =>
    "    " + offsets.slice(i * 12, i * 12 + 12).join(", ") + ",").join("\n") + "\n];\n" +
  "pub(super) const NAMES: &[(&str, u16, u16)] = &[\n" + names.join("\n") + "\n];\n";
writeFileSync(new URL("../src/commands/search/mdq_properties.bin", import.meta.url), Uint8Array.from(bytes));
writeFileSync(new URL("../src/commands/search/mdq_property_data.rs", import.meta.url), src);
