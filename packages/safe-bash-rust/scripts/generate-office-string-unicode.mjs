// Run with Node's Unicode 17 profile after building spreadsheet-engine.
import {writeFileSync} from 'node:fs';
import {caseProperties, lowerFullCases, upperFullCases} from '../../spreadsheet-engine/dist/formulas/functions/byte-case-properties.js';
import {simpleUnicodeCase} from '../../spreadsheet-engine/dist/formulas/functions/unicode.js';
import {isUnicodeAlpha} from '../../spreadsheet-engine/dist/workbook/unicode-sheet-name.js';

if(process.versions.unicode!=='17.0')throw new Error('EXACT requires the public Unicode 17 normalization profile');
const upper=[],lower=[],properties=[],decomposition=[],combining=[];
const quote=s=>'"'+Array.from(s,c=>'\\u{'+c.codePointAt(0).toString(16)+'}').join('')+'"';
let range=0;
for(let point=0;point<=0x10ffff;point++){
  if(point>=0xd800 && point<=0xdfff)continue;
  while(range<caseProperties.length && caseProperties[range][1]<point)range++;
  const flags=range<caseProperties.length && caseProperties[range][0]<=point?caseProperties[range][2]:0;
  const c=String.fromCodePoint(point);
  for(const [flag,full,output,uppercase] of [[2,upperFullCases,upper,true],[1,lowerFullCases,lower,false]]){
    if(!(flags&flag))continue;
    const mapped=full.get(point)??simpleUnicodeCase(point,uppercase);
    if(mapped!==c)output.push([point,mapped]);
  }
  const property=(isUnicodeAlpha(point)?1:0)|(flags&4?2:0),last=properties.at(-1);
  if(property){
    if(last && last[1]===point-1 && last[2]===property)last[1]=point;
    else properties.push([point,point,property]);
  }
  if(point>=0xac00 && point<=0xd7a3)continue; // Hangul decomposition is algorithmic.
  const nfd=c.normalize('NFD');
  if(nfd!==c)decomposition.push([point,nfd]);
  else if(('a\u0345'+c).normalize('NFD')!=='a\u0345'+c || ('a'+c+'\u0334').normalize('NFD')!=='a'+c+'\u0334')combining.push(c);
}
// NFD exposes the ordering relation without depending on another ICU/UCD version.
// Class ranks preserve that relation and equal-class stability; numeric CCCs are unused.
function compare(a,b){
  if(('a'+a+b).normalize('NFD')!=='a'+a+b)return 1;
  return ('a'+b+a).normalize('NFD')!=='a'+b+a?-1:0;
}
combining.sort(compare);
let rank=0,previous;
const classes=combining.map(c=>{
  if(previous===undefined || compare(previous,c)!==0)rank++;
  previous=c;return [c.codePointAt(0),rank];
}).sort((a,b)=>a[0]-b[0]);
let output='// Generated by generate-office-string-unicode.mjs. See LICENSE.UNICODE.\n// Casing: GLib Unicode 16.0.0; canonical decomposition/order: Unicode 17.0.0.\n';
for(const [name,type,rows] of [
  ['UPPER','(u32, &str)',upper.map(([p,s])=>'('+p+','+quote(s)+')')],
  ['LOWER','(u32, &str)',lower.map(([p,s])=>'('+p+','+quote(s)+')')],
  ['PROPERTIES','(u32,u32,u8)',properties.map(r=>'('+r.join(',')+')')],
  ['DECOMPOSE','(u32, &str)',decomposition.map(([p,s])=>'('+p+','+quote(s)+')')],
  ['CLASSES','(u32,u8)',classes.map(r=>'('+r.join(',')+')')],
]){
  output+='#[rustfmt::skip]\npub(super) const '+name+': &['+type+'] = &[\n';
  for(let i=0;i<rows.length;i+=4)output+='    '+rows.slice(i,i+4).join(',')+',\n';
  output+='];\n';
}
writeFileSync(new URL('../src/commands/office_formula_string_unicode.rs',import.meta.url),output);
console.log({upper:upper.length,lower:lower.length,properties:properties.length,decomposition:decomposition.length,classes:classes.length,ranks:rank});
