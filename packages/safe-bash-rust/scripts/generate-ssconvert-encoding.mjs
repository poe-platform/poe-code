// Run after building spreadsheet-engine. Runtime tables remain dependency-free.
import {writeFileSync} from 'node:fs';
import {singleByteTables,encodingAliases} from '../../spreadsheet-engine/dist/encoding/tables.js';
import {encodingName} from '../../spreadsheet-engine/dist/encoding/names.js';
import {nativeTextCharsets} from '../../spreadsheet-engine/dist/codecs/native-text-charsets.js';
import {shiftJisEncoding,shiftJisDecoder} from '../../spreadsheet-engine/dist/encoding/shift-jis.js';
import {cTransliterations,utf8Transliterations} from '../../spreadsheet-engine/dist/encoding/transliteration-tables.js';
import {cTargetTransliterations,utf8TargetTransliterations} from '../../spreadsheet-engine/dist/encoding/target-transliteration-tables.js';
import {utf8Ucs2Transliterations} from '../../spreadsheet-engine/dist/encoding/ucs2-transliteration-tables.js';

const quote=s=>'"'+Array.from(s,c=>'\\u{'+c.codePointAt(0).toString(16)+'}').join('')+'"';
const scalarEntries=entries=>Array.from(entries,([c,v])=>[c.codePointAt(0),v]).sort((a,b)=>a[0]-b[0]);
let output='// Generated by scripts/generate-ssconvert-encoding.mjs.\n// glibc 2.41 encoding observations: LGPL-2.1-or-later; see LICENSE.GLIB.\n\n';
function table(name,type,rows){output+=`#[rustfmt::skip]\npub(in super::super) static ${name}: &[${type}] = &[\n`;for(let i=0;i<rows.length;i+=4)output+='    '+rows.slice(i,i+4).join(', ')+',\n';output+='];\n\n';}
const names=new Set([...nativeTextCharsets,...Object.keys(encodingAliases),...Object.keys(singleByteTables)]);
table('ALIASES','(&str, &str)',[...names].sort().filter(name=>name!==encodingName(name)).map(name=>`(${JSON.stringify(name)}, ${JSON.stringify(encodingName(name))})`));
table('NATIVE','&str',[...nativeTextCharsets].sort().map(name=>JSON.stringify(name)));
const mappings=Object.entries(singleByteTables).map(([name,table])=>[name,new Map(Array.from(table,(c,i)=>[c,i]).filter(([c])=>c!=='\uffff'))]);
mappings.push(['shift_jis',shiftJisEncoding()]);mappings.sort(([a],[b])=>a<b?-1:1);
for(const [i,[,mapping]] of mappings.entries())table('MAP_'+i,'(u32, u16)',scalarEntries(mapping).map(([c,v])=>`(0x${c.toString(16)}, 0x${v.toString(16)})`));
table('MAPPINGS','(&str, &[(u32, u16)])',mappings.map(([name],i)=>`(${JSON.stringify(name)}, MAP_${i})`));
const decoding=Object.entries(singleByteTables).sort(([a],[b])=>a<b?-1:1);
for(const [i,[,characters]] of decoding.entries()){
 const units=Array.from(characters,c=>c.codePointAt(0));
 if(units.length!==256||units.some(c=>c>65535))throw new Error('Expected a BMP single-byte repertoire');
 table('DECODE_'+i,'u16',units.map(c=>'0x'+c.toString(16)));
}
table('DECODING','(&str, &[u16])',decoding.map(([name],i)=>`(${JSON.stringify(name)}, DECODE_${i})`));
const pairs=[];
for(let lead=0x81;lead<=0xea;lead++)for(let trail=0;trail<=255;trail++){
 if(lead>0x9f&&lead<0xe0)continue;
 try{const decoded=shiftJisDecoder()(Uint8Array.of(lead,trail));if(decoded.length===1)pairs.push(`(0x${(lead*256+trail).toString(16)}, 0x${decoded.charCodeAt(0).toString(16)})`);}catch { /* Invalid byte pairs are absent from the decoding table. */ }
}
table('SHIFT_JIS_DECODING','(u16, u16)',pairs);
// The automatic text opener uses Unicode general categories, independently of encoding.
const nonprinting=[];
for(let c=0;c<=0x10ffff;c++)if(/[\p{Cc}\p{Cf}\p{Cn}\p{Cs}]/u.test(String.fromCodePoint(c))){
 const last=nonprinting.at(-1);if(last&&last[1]===c-1)last[1]=c;else nonprinting.push([c,c]);
}
output+='// Unicode '+process.versions.unicode+' general categories; see LICENSE.UNICODE.\n';
table('NONPRINTING','(u32, u32)',nonprinting.map(([a,b])=>`(0x${a.toString(16)}, 0x${b.toString(16)})`));
for(const [name,mapping] of [['C',cTransliterations],['UTF8',utf8Transliterations],['UCS2',utf8Ucs2Transliterations]])table(name,'(u32, &str)',scalarEntries(Object.entries(mapping)).map(([c,v])=>`(0x${c.toString(16)}, ${quote(v)})`));
for(const [name,targets] of [['C_TARGETS',cTargetTransliterations],['UTF8_TARGETS',utf8TargetTransliterations]]){
 const entries=Object.entries(targets).sort(([a],[b])=>a<b?-1:1);
 for(const [i,[,mapping]] of entries.entries())table(name+'_'+i,'(u32, &str)',scalarEntries(Object.entries(mapping)).map(([c,v])=>`(0x${c.toString(16)}, ${quote(v)})`));
 table(name,'(&str, &[(u32, &str)])',entries.map(([charset],i)=>`(${JSON.stringify(charset)}, ${name}_${i})`));
}
writeFileSync(new URL('../src/commands/ssconvert_encoding_tables.rs',import.meta.url),output);
console.log({bytes:output.length,encodings:mappings.length,aliases:[...names].filter(name=>name!==encodingName(name)).length});
