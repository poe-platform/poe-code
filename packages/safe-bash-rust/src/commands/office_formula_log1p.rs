// Match the production spreadsheet engine's 192-bit log(1+x) series.
// Four little-endian limbs hold the fractional bits and the integer part.
pub(super) fn log1p(x: f64) -> f64 {
    if x <= -1. || x.is_nan() {
        return f64::NAN;
    }
    if !x.is_finite() || x.abs() < 2.7755575615628914e-17 {
        return x;
    }
    let bits = x.abs().to_bits();
    let exponent = (bits >> 52) as i32 - 1075;
    let mantissa = (bits & ((1 << 52) - 1)) | (1 << 52);
    let unit = [0, 0, 0, 1];
    let (normalized, power) = if exponent < 0 {
        // The tiny-input branch bounds -exponent by 107, so 1+x fits u128.
        let one = 1u128 << -exponent;
        let value = if x < 0. {
            one - mantissa as u128
        } else {
            one + mantissa as u128
        };
        let length = 128 - value.leading_zeros();
        (
            shift([value as u64, (value >> 64) as u64, 0, 0], 193 - length),
            length as i32 - 1 + exponent,
        )
    } else {
        let mut power = exponent + 52;
        let mut value = shift([mantissa, 0, 0, 0], 140);
        if power <= 192 {
            value = add(value, shift([1, 0, 0, 0], (192 - power) as u32));
        }
        if value[3] == 2 {
            // 1 + (2^53 - 1) crosses the normalization boundary.
            value = unit;
            power += 1;
        }
        (value, power)
    };
    let denominator = add(normalized, unit);
    let mut remainder = subtract(normalized, unit);
    let mut ratio = [0; 4];
    for bit in (0..192).rev() {
        remainder = shift(remainder, 1);
        if remainder.iter().rev().cmp(denominator.iter().rev()).is_ge() {
            remainder = subtract(remainder, denominator);
            ratio[bit / 64] |= 1 << (bit % 64);
        }
    }
    let square = multiply(ratio, ratio);
    let mut term = ratio;
    let mut sum = ratio;
    for odd in (3..257).step_by(2) {
        term = multiply(term, square);
        if term == [0; 4] {
            break;
        }
        let mut quotient = [0; 4];
        let mut remainder = 0u128;
        for index in (0..4).rev() {
            let value = (remainder << 64) | term[index] as u128;
            quotient[index] = (value / odd) as u64;
            remainder = value % odd;
        }
        sum = add(sum, quotient);
    }
    // floor(log(2)*2^192), as independently generated by production.
    let mut scaled_log_two = [0; 4];
    let mut carry = 0u128;
    for (index, limb) in [
        0x40f343267298b62du64,
        0xc9e3b39803f2f6af,
        0xb17217f7d1cf79ab,
        0,
    ]
    .into_iter()
    .enumerate()
    {
        let value = limb as u128 * power.unsigned_abs() as u128 + carry;
        scaled_log_two[index] = value as u64;
        carry = value >> 64;
    }
    let doubled = shift(sum, 1);
    let magnitude = if power < 0 {
        subtract(scaled_log_two, doubled)
    } else {
        add(scaled_log_two, doubled)
    };
    let top = magnitude.iter().rposition(|&word| word != 0).unwrap();
    let length = top * 64 + 64 - magnitude[top].leading_zeros() as usize;
    let discarded = length - 53;
    let bit = |index: usize| magnitude[index / 64] >> (index % 64) & 1;
    let mut significant = 0u64;
    for index in (discarded..length).rev() {
        significant = significant * 2 + bit(index);
    }
    if bit(discarded - 1) != 0 && (significant & 1 != 0 || (0..discarded - 1).any(|i| bit(i) != 0))
    {
        significant += 1;
    }
    let result = significant as f64 * f64::from_bits(((discarded + 1023 - 192) as u64) << 52);
    if power < 0 { -result } else { result }
}

fn shift(value: [u64; 4], bits: u32) -> [u64; 4] {
    let words = bits as usize / 64;
    let bits = bits % 64;
    std::array::from_fn(|index| {
        if index < words {
            0
        } else {
            (value[index - words] << bits)
                | if bits != 0 && index > words {
                    value[index - words - 1] >> (64 - bits)
                } else {
                    0
                }
        }
    })
}

fn add(left: [u64; 4], right: [u64; 4]) -> [u64; 4] {
    let mut carry = 0u128;
    std::array::from_fn(|index| {
        let value = left[index] as u128 + right[index] as u128 + carry;
        carry = value >> 64;
        value as u64
    })
}

fn subtract(left: [u64; 4], right: [u64; 4]) -> [u64; 4] {
    let mut borrow = false;
    std::array::from_fn(|index| {
        let (value, first) = left[index].overflowing_sub(right[index]);
        let (value, second) = value.overflowing_sub(u64::from(borrow));
        borrow = first || second;
        value
    })
}

// Discard the low 192 fractional bits after the exact limb multiplication.
fn multiply(left: [u64; 4], right: [u64; 4]) -> [u64; 4] {
    let mut product = [0u64; 8];
    for (i, a) in left.into_iter().enumerate() {
        let mut carry = 0u128;
        for (j, b) in right.into_iter().enumerate() {
            let value = a as u128 * b as u128 + product[i + j] as u128 + carry;
            product[i + j] = value as u64;
            carry = value >> 64;
        }
        product[i + 4] = carry as u64;
    }
    product[3..7].try_into().unwrap()
}
