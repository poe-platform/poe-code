use super::statistics::math::EXP_TABLE;

pub(super) fn pow(x: f64, y: f64) -> f64 {
    // These exact special cases need no log/exp approximation.
    if x == 0.
        || !x.is_finite()
        || !y.is_finite()
        || y.abs() < 2.710505431213761e-20
        || y.abs() >= 9223372036854775808.
        || x < 0. && y.fract() != 0.
    {
        return x.powf(y);
    }
    let negative = x < 0. && y % 2. != 0.;
    let mut ix = x.abs().to_bits();
    if ix >> 52 == 0 {
        ix = (x.abs() * 4503599627370496.)
            .to_bits()
            .wrapping_sub(52 << 52);
    }
    // Reduce x to a table interval and retain the low bits of log(x).
    let tmp = ix.wrapping_sub(0x3fe6955500000000);
    let index = ((tmp >> 45) % 128) as usize;
    let kd = ((tmp as i64) >> 52) as f64;
    let iz = ix.wrapping_sub(tmp & (0xfff << 52));
    let z = f64::from_bits(iz);
    let [invc, logc, logctail] = LOG_TABLE[index];
    let zhi = f64::from_bits((iz + (1 << 31)) & (u64::MAX << 32));
    let zlo = z - zhi;
    let rhi = zhi * invc - 1.;
    let rlo = zlo * invc;
    let r = rhi + rlo;
    let t1 = kd * 0.6931471805598903 + logc;
    let t2 = t1 + r;
    let lo1 = kd * 5.497923018708371e-14 + logctail;
    let lo2 = t1 - t2 + r;
    let ar = -0.5 * r;
    let ar2 = r * ar;
    let ar3 = r * ar2;
    let arhi = -0.5 * rhi;
    let arhi2 = rhi * arhi;
    let hi = t2 + arhi2;
    let lo3 = rlo * (ar + arhi);
    let lo4 = t2 - hi + arhi2;
    let p = ar3
        * (-0.6666666666666679
            + r * 0.5000000000000007
            + ar2
                * (0.7999999995323976
                    + r * -0.6666666663487739
                    + ar2 * (-1.142909628459501 + r * 1.0000415263675542)));
    let lo = lo1 + lo2 + lo3 + lo4 + p;
    let high = hi + lo;
    let low = hi - high + lo;
    // Multiply the split logarithm without losing its correction term.
    let yhi = f64::from_bits(y.to_bits() & (u64::MAX << 27));
    let ylo = y - yhi;
    let lhi = f64::from_bits(high.to_bits() & (u64::MAX << 27));
    let llo = high - lhi + low;
    let ehi = yhi * lhi;
    let elo = ylo * lhi + y * llo;
    let result = exp_tail(ehi, elo);
    if negative { -result } else { result }
}
fn exp_tail(x: f64, xtail: f64) -> f64 {
    let absolute = x.abs();
    if absolute < 5.551115123125783e-17 {
        return 1. + x;
    }
    if absolute >= 1024. {
        return if x < 0. { 0. } else { f64::INFINITY };
    }
    let rounded = x * 184.6649652337873 + 6755399441055744.0;
    let ki = rounded.to_bits();
    let kd = rounded - 6755399441055744.0;
    let r = (x + kd * -0.005415212348111709 + kd * -1.2864023111638346e-14) + xtail;
    let [tail, scale_bits] = EXP_TABLE[(ki % 128) as usize];
    let mut scale_bits = scale_bits.wrapping_add(ki << 45);
    let r2 = r * r;
    let correction = f64::from_bits(tail)
        + r
        + r2 * (0.49999999999996786 + r * 0.16666666666665886)
        + r2 * r2 * (0.0416666808410674 + r * 0.008333335853059549);
    if absolute < 512. {
        let scale = f64::from_bits(scale_bits);
        // Match native fused rounding without a separately rounded product.
        return scale.mul_add(correction, scale);
    }
    if ki & 0x8000_0000 == 0 {
        scale_bits = scale_bits.wrapping_sub(1009 << 52);
        let scale = f64::from_bits(scale_bits);
        return f64::from_bits((1023 + 1009) << 52) * (scale + scale * correction);
    }
    scale_bits = scale_bits.wrapping_add(1022 << 52);
    let scale = f64::from_bits(scale_bits);
    let mut value = scale + scale * correction;
    if value < 1. {
        let low = scale - value + scale * correction;
        let high = 1. + value;
        let low = 1. - high + value + low;
        value = high + low - 1.;
    }
    f64::MIN_POSITIVE * value
}

