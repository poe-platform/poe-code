pub(in crate::commands) fn quote_sheet(name: &str) -> String {
    if name.starts_with('\'') && name.ends_with('\'') {
        return name.to_owned();
    }
    let simple = name.chars().enumerate().all(|(i, c)| {
        let code = c as u32;
        c == '_'
            || IDENTIFIERS
                .binary_search_by(|&(first, last, _)| {
                    if code < first {
                        std::cmp::Ordering::Greater
                    } else if code > last {
                        std::cmp::Ordering::Less
                    } else {
                        std::cmp::Ordering::Equal
                    }
                })
                .is_ok_and(|index| match IDENTIFIERS[index].2 {
                    2 => i > 0,
                    3 => i == 0,
                    _ => true,
                })
    });
    if simple && !name.bytes().all(|b| b.is_ascii_digit()) {
        name.to_owned()
    } else {
        format!("'{}'", name.replace('\'', "''"))
    }
}

pub(in crate::commands) fn quote_gnumeric_sheet(name: &str) -> String {
    if name.is_empty() {
        return String::new();
    }
    let simple = name.chars().enumerate().all(|(i, c)| {
        c == '_' || i > 0 && (c.is_ascii_digit() || c == '.') || {
            let code = c as u32;
            let index = ALPHABETIC.partition_point(|&(_, end)| end < code);
            ALPHABETIC
                .get(index)
                .is_some_and(|&(start, _)| start <= code)
        }
    });
    let letters = name.bytes().take_while(u8::is_ascii_alphabetic).count();
    let column = name[..letters].bytes().fold(0usize, |value, c| {
        value
            .saturating_mul(26)
            .saturating_add(usize::from(c.to_ascii_uppercase() - b'A' + 1))
    });
    let row = &name[letters..];
    let cell = letters > 0
        && column <= 16_384
        && row.bytes().all(|c| c.is_ascii_digit())
        && row
            .parse::<u32>()
            .is_ok_and(|row| (1..=16_777_216).contains(&row));
    if simple && !cell {
        name.to_owned()
    } else {
        format!("'{}'", name.replace('\\', "\\\\").replace('\'', "\\'"))
    }
}

