// Temme's incomplete-gamma expansion near large shape parameters.
use super::super::math;

pub(in super::super) fn log1pmx(x: f64, work: &mut usize) -> Option<f64> {
    if x.abs() > 0.5 {
        return Some(x.ln_1p() - x);
    }
    let mut term = -x * x;
    let mut sum = term / 2.;
    let mut n = 2.;
    loop {
        *work = work.checked_sub(1)?;
        term *= -x;
        n += 1.;
        let next = sum + term / n;
        if next == sum {
            return Some(sum);
        }
        sum = next;
    }
}

