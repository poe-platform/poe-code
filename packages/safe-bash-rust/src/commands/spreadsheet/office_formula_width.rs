pub(super) fn convert(text: &str, half: bool, work: &mut usize) -> Option<Value> {
    *work = work.checked_sub(text.len())?;
    let mut chars = text.chars().peekable();
    let mut output = String::new();
    let mut units = 0usize;
    while let Some(c) = chars.next() {
        let (first, second) = if half {
            narrow(c)
        } else {
            let c = wide(c);
            let composed = chars.peek().and_then(|&next| compose(c, wide(next)));
            if composed.is_some() {
                chars.next();
            }
            (composed.unwrap_or(c), None)
        };
        for c in std::iter::once(first).chain(second) {
            units += c.len_utf16();
            if units > 32767 {
                return Some(Value::Error("#VALUE!"));
            }
            *work = work.checked_sub(c.len_utf8())?;
            output.push(c);
        }
    }
    Some(Value::Text(output))
}
