// Calc compares sheet and defined names using simple uppercase, without ß → SS.
pub fn sheet_key(name: &str) -> String {
    name.chars().map(uppercase).collect()
}

pub(in crate::commands) fn same_name(a: &str, b: &str) -> bool {
    a.chars().map(uppercase).eq(b.chars().map(uppercase))
}

