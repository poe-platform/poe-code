use std::fmt::Write;

pub(super) const ASS_HEADER: &str = "[Script Info]\r\n; Script generated by FFmpeg/Lavc61.19.100\r\nScriptType: v4.00+\r\nPlayResX: 384\r\nPlayResY: 288\r\nScaledBorderAndShadow: yes\r\nYCbCr Matrix: None\r\n\r\n[V4+ Styles]\r\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\r\nStyle: Default,Arial,16,&Hffffff,&Hffffff,&H0,&H0,0,0,0,0,100,100,0,0,1,1,0,2,10,10,10,1\r\n\r\n[Events]\r\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\r\n";

pub(super) struct Cue {
    pub start: i64,
    pub duration: i64,
    pub text: String,
}

// The native subtitle queue finishes at the lower member of its last search pair.
pub(super) fn seek_index<T>(packets: &[T], ts: i64, timing: impl Fn(&T) -> (i64, i64)) -> usize {
    if packets.len() < 2 { return 0; }
    let mut index = packets.partition_point(|p| timing(p).0 <= ts).saturating_sub(1).min(packets.len() - 2);
    let selected = timing(&packets[index]).0;
    for i in (0..index).rev() {
        let (pts, duration) = timing(&packets[i]);
        if duration <= 0 { continue; }
        if pts > selected.saturating_sub(duration) { index = i; } else { break; }
    }
    while index > 0 && timing(&packets[index - 1]).0 == timing(&packets[index]).0 { index -= 1; }
    index
}

fn milliseconds(raw: &str) -> i64 {
    let raw = raw.trim().replace(',', ".");
    let mut parts = raw.rsplit(':');
    let sec = parts
        .next()
        .and_then(|s| s.parse::<f64>().ok())
        .unwrap_or(0.);
    let min = parts
        .next()
        .and_then(|s| s.parse::<i64>().ok())
        .unwrap_or(0);
    let hour = parts
        .next()
        .and_then(|s| s.parse::<i64>().ok())
        .unwrap_or(0);
    ((hour as f64 * 3600. + min as f64 * 60. + sec) * 1000.).round() as i64
}

pub(super) fn cues(text: &str, verbatim: bool) -> impl Iterator<Item = Cue> + '_ {
    let mut lines = text.trim_start_matches('\u{feff}').lines();
    std::iter::from_fn(move || {
        loop {
            let first = lines.by_ref().find(|s| !s.trim().is_empty())?;
            let mut block =
                std::iter::once(first).chain(lines.by_ref().take_while(|s| if verbatim { !s.is_empty() } else { !s.trim().is_empty() }));
            if first.starts_with("WEBVTT") || first.starts_with("NOTE") {
                block.for_each(drop);
                continue;
            }
            let Some((left, right)) = block.find_map(|s| s.split_once("-->")) else {
                continue;
            };
            let start = milliseconds(left);
            let end = milliseconds(right.split_ascii_whitespace().next().unwrap_or(""));
            let mut text = String::new();
            for line in block {
                if !text.is_empty() {
                    text.push('\n')
                }
                text.push_str(if verbatim { line } else { line.trim_end() });
            }
            let text = if verbatim { text.as_str() } else { text.trim_start() };
            if !text.is_empty() {
                return Some(Cue {
                    start,
                    duration: if verbatim { end.saturating_sub(start) } else { end.saturating_sub(start).max(1) },
                    text: text.into(),
                });
            }
        }
    })
}

// MP4 timed text fills gaps with empty samples and prefixes each cue with its byte length.
pub(super) fn samples(text: &str) -> impl Iterator<Item = (Cue, bool)> + '_ {
    let packed = cues(text, false).all(|cue| {
        let bytes = cue.text.as_bytes();
        bytes.len() >= 2 && usize::from(u16::from_be_bytes([bytes[0], bytes[1]])) == bytes.len() - 2
    });
    let mut cursor = 0;
    cues(text, false).flat_map(move |mut cue| {
        let mut gap = None;
        if !packed {
            if cue.start > cursor {
                gap = Some(Cue {
                    start: cursor,
                    duration: cue.start - cursor,
                    text: String::new(),
                });
            }
            cue.start = cursor.max(cue.start);
            cursor = cue.start.saturating_add(cue.duration);
        }
        gap.into_iter()
            .chain(std::iter::once(cue))
            .map(move |c| (c, !packed))
    })
}

// Keep the portion of the first packet before a cut. MP4 hides it with an edit list.
pub(super) fn packets(
    text: &str,
    slice: Option<(f64, Option<f64>)>,
) -> impl Iterator<Item = (Vec<u8>, i64, i64, i64)> + '_ {
    let range = slice.map(|(start, end)| {
        let length = cues(text, false)
            .map(|c| c.start.saturating_add(c.duration))
            .max()
            .unwrap_or(0);
        (
            (start * 1000.).round() as i64,
            end.map_or(length, |s| ((s * 1000.).round() as i64).min(length)),
        )
    });
    samples(text).filter_map(move |(c, wrap)| {
        let mut duration = c.duration;
        let mut skip = 0;
        if let Some((start, end)) = range {
            if end <= start || c.start >= end || c.start.saturating_add(duration) <= start {
                return None;
            }
            duration = duration.min(end.saturating_sub(c.start));
            skip = start.saturating_sub(c.start).max(0);
        }
        let data = if wrap {
            let mut b = Vec::with_capacity(c.text.len() + 2);
            b.extend_from_slice(&(c.text.len() as u16).to_be_bytes());
            b.extend_from_slice(c.text.as_bytes());
            b
        } else {
            c.text.into_bytes()
        };
        Some((data, duration, skip, c.start))
    })
}

pub(super) fn timestamp(out: &mut String, ms: i64, sep: char, short: bool) {
    let ms = ms.max(0);
    if !short || ms >= 3600000 {
        write!(out, "{:02}:", if short { ms / 3600000 } else { i64::from((ms / 3600000) as i32) }).unwrap();
    }
    write!(
        out,
        "{:02}:{:02}{sep}{:03}",
        if short { ms / 60000 % 60 } else { i64::from((ms / 60000) as i32 % 60) },
        if short { ms / 1000 % 60 } else { i64::from((ms / 1000) as i32 % 60) },
        ms % 1000
    )
    .unwrap();
}

pub(super) struct Writer<'a> {
    pub output: String,
    index: usize,
    pub(super) format: &'a str,
    pub(super) limit: usize,
}

impl<'a> Writer<'a> {
    pub fn new(format: &'a str, limit: usize) -> Self {
        Self {
            output: if format == "webvtt" {
                "WEBVTT\n".into()
            } else if format == "ass" {
                ASS_HEADER.replace("\r\n", "\n")
            } else {
                String::new()
            },
            index: 0,
            format,
            limit,
        }
    }

    pub fn cue(&mut self, start: i64, end: i64, body: &str) -> Result<(), &'static str> {
        if self.format == "ttml" { return super::ttml::cue(&mut self.output, start, end, body, self.limit); }
        if self.format == "lrc" { return super::lrc::write_cue(&mut self.output, start, body, self.limit); }
        if self.format == "ass" {
            let pts = start.saturating_add(start.signum() * 5) / 10;
            let duration = end.saturating_sub(start);
            let duration = duration.saturating_add(duration.signum() * 5) / 10;
            writeln!(self.output, "Dialogue: 0,{},{},Default,,0,0,0,,{}", super::ass::timestamp(pts), super::ass::timestamp(pts.saturating_add(duration)), super::ass::from_html(body)).unwrap();
            return if self.output.len() > self.limit { Err("output byte limit exceeded") } else { Ok(()) };
        }
        if body.len() > self.limit.saturating_sub(self.output.len()) {
            return Err("output byte limit exceeded");
        }
        let out = &mut self.output;
        if self.format == "webvtt" { out.push('\n'); }
        self.index += 1;
        if self.format != "webvtt" {
            writeln!(out, "{}", self.index).unwrap();
        }
        let sep = if self.format == "webvtt" { '.' } else { ',' };
        timestamp(out, start, sep, self.format == "webvtt");
        out.push_str(" --> ");
        timestamp(out, end, sep, self.format == "webvtt");
        out.push('\n');
        let last = body.split('\n').count().saturating_sub(1);
        for (index, line) in body.split('\n').enumerate() {
            if index != 0 { out.push_str(if self.format == "srt" { "\r\n" } else { "\n" }); }
            out.push_str(if self.format == "srt" && index < last { line.strip_suffix('\r').unwrap_or(line) } else { line });
        }
        out.push('\n');
        if self.format != "webvtt" { out.push('\n'); }
        if out.len() > self.limit {
            return Err("output byte limit exceeded");
        }
        Ok(())
    }
}

pub(super) fn convert(
    text: &str,
    writer: &mut Writer,
    slice: Option<(f64, Option<f64>)>,
) -> Result<(), &'static str> {
    if slice.is_some() {
        let mut dts = 0i64;
        for (body, duration, _, _) in packets(text, slice) {
            writer.cue(
                dts,
                dts.saturating_add(duration),
                &String::from_utf8_lossy(&body),
            )?;
            dts = dts.saturating_add(duration);
        }
    } else {
        for c in cues(text, false) {
            writer.cue(c.start, c.start.saturating_add(c.duration), &c.text)?
        }
    }
    Ok(())
}

fn probe_clock(rest: &mut &[u8], webvtt: bool) -> Option<i64> {
    use super::text_subtitles::number;
    for fields in if webvtt { &[3, 2][..] } else { &[3][..] } {
        let mut tail = *rest;
        let value = (|| {
            let mut seconds = 0;
            for field in 0..*fields {
                if field > 0 { tail = tail.strip_prefix(b":")?; }
                seconds = seconds * 60 + number(&mut tail, usize::MAX)?;
            }
            tail = if webvtt { tail.strip_prefix(b".")? } else {
                tail.strip_prefix(b".").or_else(|| tail.strip_prefix(b","))?
            };
            Some(seconds * 1000 + number(&mut tail, usize::MAX)?)
        })();
        if let Some(value) = value { *rest = tail; return Some(value); }
    }
    None
}

pub(super) fn read(bytes: &[u8], webvtt: bool, remaining: &mut usize) -> Result<super::lrc::Document, &'static str> {
    use super::lrc::{Document, Packet};
    use std::borrow::Cow;
    let utf16 = !webvtt && (bytes.starts_with(b"\xff\xfe") || bytes.starts_with(b"\xfe\xff"));
    let data = if utf16 {
        let little = bytes[0] == 255;
        Cow::Owned(char::decode_utf16(bytes[2..].chunks_exact(2).map(|p| if little { u16::from_le_bytes([p[0], p[1]]) } else { u16::from_be_bytes([p[0], p[1]]) })).map(|c| c.unwrap_or('\0')).collect::<String>().into_bytes())
    } else { Cow::Borrowed(if webvtt { bytes } else { bytes.strip_prefix(b"\xef\xbb\xbf").unwrap_or(bytes) }) };
    let mut used = bytes.len().saturating_add(if utf16 { data.len() } else { 0 });
    if used > *remaining { return Err("subtitle text exceeds memory budget"); }
    let mut doc = Document {
        format: if webvtt { "webvtt" } else { "srt" }, time_base:(1,1000),
        packets:Vec::new(), tags:Vec::new(), ass_header:None, extradata_size:0,
        extradata:Vec::new(), decoded:Default::default(), packet_side_data:Default::default(),
    };
    let append = |body: &mut Vec<u8>, line: &[u8], used: &mut usize| -> Result<(), &'static str> {
        *used = used.saturating_add(line.len()).saturating_add(1);
        if *used > *remaining { return Err("subtitle packets exceed memory budget"); }
        body.extend_from_slice(line); body.push(b'\n'); Ok(())
    };
    let (mut pos, mut physical) = (0, if utf16 { 2 } else { bytes.len() - data.len() });
    let mut current: Option<Packet> = None;
    let mut cached: &[u8] = &[];
    loop {
        if webvtt {
            // Native WebVTT chunks end after two line breaks and retain internal CR/LF bytes.
            while data.get(pos).is_some_and(|b| matches!(b, b'\r' | b'\n')) { pos += 1; }
            let start = pos;
            let (mut end, mut breaks, mut cr, mut pending) = (pos, 0, false, 0);
            while let Some(&byte) = data.get(pos) {
                pos += 1;
                if byte == 0 { break; }
                if matches!(byte, b'\r' | b'\n') {
                    breaks += usize::from(byte == b'\n' || cr); pending += 1;
                    if breaks == 2 || pending == 4 { break; }
                    cr = byte == b'\r';
                } else { breaks = 0; pending = 0; end = pos; }
            }
            let chunk = &data[start..end];
            if chunk.is_empty() { break; }
            if [b"WEBVTT".as_slice(), b"\xef\xbb\xbfWEBVTT", b"STYLE", b"REGION", b"NOTE"].iter().any(|prefix| chunk.starts_with(prefix)) { continue; }
            let first = chunk.iter().position(|b| matches!(b, b'\r' | b'\n')).unwrap_or(chunk.len());
            let identified = !chunk[..first].windows(3).any(|b| b == b"-->");
            let mut tail = if identified { chunk[first..].strip_prefix(b"\r").unwrap_or(&chunk[first..]).strip_prefix(b"\n").unwrap_or(&chunk[first..]) } else { chunk };
            let Some(pts) = probe_clock(&mut tail, true) else { break; };
            let Some(arrow) = tail.windows(3).position(|b| b == b"-->") else { break; };
            tail = tail[arrow + 3..].trim_ascii_start();
            let Some(end) = probe_clock(&mut tail, true) else { break; };
            let line_end = tail.iter().position(|b| matches!(b, b'\r' | b'\n')).unwrap_or(tail.len());
            let settings = !tail[..line_end].trim_ascii().is_empty();
            tail = &tail[line_end..];
            tail = tail.strip_prefix(b"\r").unwrap_or(tail);
            tail = tail.strip_prefix(b"\n").unwrap_or(tail);
            used = used.saturating_add(size_of::<Packet>()).saturating_add(tail.len());
            if used > *remaining { return Err("subtitle packets exceed memory budget"); }
            doc.packets.push(Packet { pts, duration:end - pts, pos, data:tail.to_vec() });
            if identified || settings {
                used = used.saturating_add(size_of::<(usize, Vec<&str>)>() + (usize::from(identified) + usize::from(settings)) * size_of::<&str>());
                if used > *remaining { return Err("subtitle packets exceed memory budget"); }
                let mut names = Vec::new();
                if identified { names.push("WebVTT ID"); }
                if settings { names.push("WebVTT Settings"); }
                doc.packet_side_data.insert(pos, names);
            }
            continue;
        }
        let position = physical + usize::from(utf16 && pos != 0);
        let line = if pos < data.len() && data[pos] != 0 {
            let end = data[pos..].iter().take(4095).position(|b| matches!(b, b'\r' | b'\n' | 0)).map_or((pos + 4095).min(data.len()), |i| pos + i);
            if data.get(end) == Some(&0) { None } else {
                let mut next = end + usize::from(data.get(end).is_some_and(|b| matches!(b, b'\r' | b'\n')));
                while data.get(next) == Some(&b'\r') { next += 1; }
                if data.get(next) == Some(&b'\n') { next += 1; }
                physical += if utf16 {
                    let mut begin = pos;
                    let mut finish = next;
                    while begin > 0 && data.get(begin).is_some_and(|b| b & 0xc0 == 0x80) { begin -= 1; }
                    while finish > 0 && data.get(finish).is_some_and(|b| b & 0xc0 == 0x80) { finish -= 1; }
                    std::str::from_utf8(&data[begin..finish]).unwrap().encode_utf16().count() * 2
                } else { next - pos };
                let line = &data[pos..end]; pos = next; Some(line)
            }
        } else { None };
        let event = line.and_then(|line| {
            let mut rest = line;
            let pts = probe_clock(&mut rest, false)?;
            rest = rest.trim_ascii_start().strip_prefix(b"-->")?;
            let end = probe_clock(&mut rest, false)?;
            let coords = rest.trim_ascii_start().strip_prefix(b"X1:").and_then(|mut s| super::text_subtitles::number(&mut s, usize::MAX)).is_some_and(|n| n != -1);
            Some((pts, (end - pts) as i32 as i64, coords))
        });
        if event.is_some() || line.is_none() {
            if let Some(mut packet) = current.take() {
                let mut number = cached;
                let standalone = super::text_subtitles::integer(&mut number).is_some_and(|n| n >= 0) && number.is_empty();
                if !cached.is_empty() && (line.is_none() || packet.data.is_empty() && !standalone) { append(&mut packet.data, cached, &mut used)?; }
                while packet.data.last() == Some(&b'\n') { packet.data.pop(); }
                if !packet.data.is_empty() { doc.packets.push(packet); }
            }
            cached = &[];
            if let Some((pts, duration, coords)) = event {
                used = used.saturating_add(size_of::<Packet>());
                if used > *remaining { return Err("subtitle packets exceed memory budget"); }
                current = Some(Packet { pts, duration, pos:position, data:Vec::new() });
                if coords {
                    used = used.saturating_add(size_of::<(usize, Vec<&str>)>() + size_of::<&str>());
                    if used > *remaining { return Err("subtitle packets exceed memory budget"); }
                    doc.packet_side_data.insert(position, vec!["Subtitle Position"]);
                }
            } else { break; }
        } else if let Some(line) = line.filter(|line| !line.is_empty()) && let Some(packet) = &mut current {
            if !cached.is_empty() { append(&mut packet.data, cached, &mut used)?; cached = &[]; }
            if super::text_subtitles::integer(&mut &line[..]).is_some_and(|n| n >= 0) { cached = line; }
            else { append(&mut packet.data, line, &mut used)?; }
        }
    }
    doc.packets.sort_unstable_by_key(|p| (p.pts, p.pos));
    for i in 1..doc.packets.len() {
        if doc.packets[i - 1].duration < 0 { doc.packets[i - 1].duration = doc.packets[i].pts - doc.packets[i - 1].pts; }
    }
    doc.packets.dedup_by(|a, b| a.pts == b.pts && a.duration == b.duration && a.data == b.data);
    *remaining -= used;
    Ok(doc)
}
