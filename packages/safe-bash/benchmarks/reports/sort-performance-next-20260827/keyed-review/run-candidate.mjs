import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { baselineCommit } from './holdouts.mjs';
import { directory, git, hash, json, prepare } from './harness.mjs';
import { runPublic } from './run-public.mjs';
import { runAccepted } from './run-accepted.mjs';
import { binding, caps } from './bind-caps.mjs';
const commit = 'b4fe4c7868b7ab7067599c6f5d10e99d143aea54';
assert.ok(readFileSync('/tmp/sort-key-review-coordination.txt', 'utf8').includes(commit));
assert.equal(JSON.parse(readFileSync(join(directory, 'baseline-v2/public.child.json'))).passed, 28);
assert.equal(hash(git(commit, 'src/commands/text.ts')), '9a66dc0e320c62aad86d78da9c55580cf6910a537a47db8a330e5122f63a1895');
const prepared = prepare(commit, 'candidate');
const evidence = join(directory, 'candidate-preparation'); mkdirSync(evidence);
json(join(evidence, 'prepared.json'), prepared);
json(join(directory, 'cap-binding.json'), { ...binding, baselineCommit, candidateCommit: commit, sourceSha256: hash(git(commit, 'src/commands/text.ts')), casesSha256: hash(JSON.stringify(caps())), recipes: caps().map(row => ({ id: row.id, inputBytes: Buffer.from(row.input, 'base64').length, account: row.account })) });
console.log(JSON.stringify(await runPublic(prepared, 'candidate-v2')));
