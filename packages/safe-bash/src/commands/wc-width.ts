function contains(ranges: readonly number[], point: number): boolean {
  let low = 0;
  let high = ranges.length / 2;
  while (low < high) {
    const middle = Math.floor((low + high) / 2);
    if (point < ranges[middle * 2]!) high = middle;
    else if (point > ranges[middle * 2 + 1]!) low = middle + 1;
    else return true;
  }
  return false;
}

export function wcDisplayWidth(point: number): number {
  if (contains(zeroWidth, point)) return 0;
  return contains(wide, point) ? 2 : 1;
}
