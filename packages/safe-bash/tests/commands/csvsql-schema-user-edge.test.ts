import test from "node:test";
import assert from "node:assert/strict";
import { Shell } from "../../src/shell/index.js";
import { MemoryFileSystem } from "../../src/fs/memory/index.js";
import { csvkitCommands } from "../../src/commands/csvkit/index.js";
import { utf8Codec, type DatabaseProvider } from "@poe-code/csvkit";

function fixture(databases: readonly DatabaseProvider[] = []) {
  const fs = new MemoryFileSystem();
  const shell = new Shell({ fs }).use(csvkitCommands({
    codecs: [utf8Codec], databases,
    locale: { profile: "C", timezone: "UTC", formatNumber: () => { throw new Error("unqualified locale"); } },
    clock: { now: () => 0 },
    terminal: { stdinIsTTY: false, stdoutIsTTY: false, stderrIsTTY: false, columns: 80, lines: 24 }
  }));
  return { fs, shell };
}

// Fresh observations from the frozen CPython 3.14.2 / csvkit 2.2.0 /
// agate-sql 0.7.3 / SQLAlchemy 2.0.54 reference, not generated by the engine.
const cases = [
  ["NaN and infinities do not contribute to scale", "-i mysql", "a,b\nNaN,Infinity\n2.34,-Infinity\n", "CREATE TABLE stdin (\n\ta DECIMAL(38, 2) NOT NULL, \n\tb DECIMAL(38, 0) NOT NULL\n);\n"],
  ["tiny decimal scale is capped", "-i mysql", "a\n0.000000000000000000000000000001\n", "CREATE TABLE stdin (\n\ta DECIMAL(38, 27) NOT NULL\n);\n"],
  ["signed zero normalizes without fractional scale", "-i mysql", "a\n-0.000\n0\n", "CREATE TABLE stdin (\n\ta DECIMAL(38, 0) NOT NULL\n);\n"],
  ["percent escaping, embedded quote and final LF identifier", "-i postgresql --tables 'a%b'", '"a%","a""b","line\n"\nx,y,z\n', 'CREATE TABLE "a%%b" (\n\t"a%%" VARCHAR NOT NULL, \n\t"a""b" BOOLEAN NOT NULL, \n\tline\n VARCHAR NOT NULL\n);\n'],
  ["blanks with inference retain required text", "-i mysql --blanks", "a,b\n,\nx,y\n", "CREATE TABLE stdin (\n\ta VARCHAR(1) NOT NULL, \n\tb VARCHAR(1) NOT NULL\n);\n"],
  ["blanks without inference retain required text", "-i mysql --blanks -I", "a,b\n,\nx,y\n", "CREATE TABLE stdin (\n\ta VARCHAR(1) NOT NULL, \n\tb VARCHAR(1) NOT NULL\n);\n"],
  ["no inference still recognizes nulls", "-i mysql -I", "a,b\n,\nx,y\n", "CREATE TABLE stdin (\n\ta VARCHAR(1), \n\tb VARCHAR(1)\n);\n"],
  ["MSSQL unconstrained columns retain explicit NULL suffix", "-i mssql --no-constraints", "a,b,c\ntrue,2020-01-01,2020-01-01T01:02:03\n", "CREATE TABLE stdin (\n\ta BIT NULL, \n\tb DATE NULL, \n\tc DATETIME NULL\n);\n"],
  ["Oracle constraints off retains explicit unique constraint", "-i oracle --no-constraints --unique-constraint flag", "flag,when,duration\ntrue,2020-01-01T01:02:03,1:02:03\nfalse,,\n", "CREATE TABLE stdin (\n\tflag BOOLEAN, \n\twhen TIMESTAMP, \n\tduration INTERVAL DAY TO SECOND, \n\tUNIQUE (flag)\n);\n"],
  ["headerless input derives generated names and nullable date", "-i sqlite -H", "x,2020-01-01\ny,\n", "CREATE TABLE stdin (\n\ta VARCHAR NOT NULL, \n\tb DATE\n);\n"]
] as const;

for (const [label, argv, stdin, stdout] of cases) {
  test(`csvsql actual shell user edge: ${label}`, async () => {
    const { shell } = fixture();
    try {
      const result = await shell.exec(`csvsql -y 0 ${argv}`, { stdin });
      assert.deepEqual([result.stdout, result.stderr, result.exitCode], [stdout, "", 0]);
    } finally { await shell.dispose(); }
  });
}

for (const [minimum, multiplier, length, text] of [
  ["0", "0", "0", "xx"], ["-1", "0", "0", "xx"], ["0", "-1", "0", "xx"], ["99999", "1", "99999", "xx"],
  ["-10000000000000000000000000000000000000000", "-123456789012345678901234567890123", "-370370367037037036703703703700000", "abc"],
  ["-10000000000000000000000000000000000000000", "-33333333333333333333333333335", "-100000000000000000000000000000", "abc"],
  ["-10000000000000000000000000000000000000000", "-33333333333333333333333333345", "-100000000000000000000000000000", "abc"]
] as const) {
  test(`csvsql actual shell connected mysql length minimum ${minimum}, multiplier ${multiplier}`, async () => {
    const effects: string[] = [];
    const databases: DatabaseProvider[] = [{ schemes: ["mysql"], profile: "user-edge-recording", async connect() {
      effects.push("connect");
      return {
        profile: "user-edge-recording", dialect: "mysql",
        async begin() { effects.push("begin"); },
        async query(sql) { effects.push(sql); return { columns: null, rows: (async function* () {})(), async close() { effects.push("result-close"); } }; },
        async commit() { effects.push("commit"); }, async rollback() { effects.push("rollback"); }, async close() { effects.push("close"); }
      };
    } }];
    const { shell } = fixture(databases);
    try {
      const result = await shell.exec(`csvsql --db mysql:// -y 0 --min-col-len ${minimum} --col-len-multiplier ${multiplier}`, { stdin: `a\n${text}\n` });
      assert.deepEqual([result.stdout, result.stderr, result.exitCode], ["", "", 0]);
      assert.deepEqual(effects, ["connect", "begin", `\nCREATE TABLE stdin (\n\ta VARCHAR(${length}) NOT NULL\n)\n\n`, "result-close", "commit", "close"]);
    } finally { await shell.dispose(); }
  });
}
