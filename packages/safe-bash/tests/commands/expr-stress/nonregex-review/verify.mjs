import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { gunzipSync } from 'node:zlib';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sha256, load, snapshot, candidateCommit, freezeCommit } from './prepare.mjs';

const base = dirname(fileURLToPath(import.meta.url));
const root = resolve(base, '../../../..');
const manifest = load(join(base, 'MANIFEST.json'));
const actual = snapshot(base).filter(entry => !entry.directory && entry.path !== 'MANIFEST.json');
assert.deepEqual(actual, manifest.files, 'review evidence byte or inventory change, including appended files');
const provenance = load(join(base, 'provenance.json'));
assert.equal(provenance.candidateCommit, candidateCommit);
assert.equal(provenance.freezeCommit, freezeCommit);
assert.equal(provenance.candidateDirty, false);
for (const entry of provenance.harnessManifest) assert.equal(sha256(readFileSync(join(base, entry.path))), entry.sha256);
const git = args => {
  const result = spawnSync('git', args, { cwd: root, timeout: 10000, maxBuffer: 16 * 1024 * 1024 });
  assert.equal(result.status, 0, result.stderr.toString());
  return result.stdout;
};
assert.equal(sha256(git(['archive', '--format=tar', candidateCommit, ...provenance.archivePaths])), provenance.candidateArchiveSha256);
assert.equal(sha256(git(['archive', '--format=tar', freezeCommit, 'tests/commands/expr-stress/frozen'])), provenance.freezeArchiveSha256);
const frozenPath = 'tests/commands/expr-stress/frozen';
const frozen = join(root, frozenPath);
assert.deepEqual(snapshot(frozen), provenance.frozenManifest);
const oracle = JSON.parse(git(['show', `${freezeCommit}:${frozenPath}/evidence/original-20260827/oracle.json`]));
const inputs = JSON.parse(git(['show', `${freezeCommit}:${frozenPath}/inputs.json`]));
const report = load(join(base, 'evidence/final/candidate-report.json'));
const comparison = load(join(base, 'evidence/final/comparison.json'));
const summary = load(join(base, 'evidence/final/summary.json'));
assert.equal(inputs.cases.length, 95);
assert.equal(report.candidate.commit, candidateCommit);
assert.equal(report.candidate.dirty, false);
assert.equal(report.candidate.adapterSha256, provenance.adapterSha256);
assert.equal(report.candidate.sourceTreeSha256, provenance.sourceTreeSha256);
assert.equal(comparison.length, 104);
assert.deepEqual(report.profiles.map(profile => [profile.id, profile.results.length]), [['gnu-9.7-darwin-C', 95], ['gnu-9.7-darwin-en_US.UTF-8', 9]]);
let semantic = 0;
let diagnostic = 0;
let strict = 0;
let offset = 0;
for (const profile of report.profiles) {
  const expectedProfile = oracle.profiles.find(entry => entry.id === profile.id);
  assert(expectedProfile);
  assert.deepEqual(profile.results.map(row => row.id), expectedProfile.results.map(row => row.id));
  for (const [index, row] of profile.results.entries()) {
    const expected = expectedProfile.results[index];
    assert.equal(row.caseSha256, expected.caseSha256);
    const sem = row.status === expected.status && row.stdoutBase64 === expected.stdoutBase64 && Boolean(row.stderrBase64) === Boolean(expected.stderrBase64) && row.failure === null;
    const diag = row.stderrBase64 === expected.stderrBase64;
    semantic += Number(sem);
    diagnostic += Number(diag);
    strict += Number(sem && diag);
    const detail = comparison[offset++];
    assert.equal(detail.profile, profile.id);
    assert.deepEqual(detail.expected, expected);
    assert.deepEqual(detail.observed, row);
    assert.equal(detail.semantic, sem);
    assert.equal(detail.diagnostic, diag);
    assert.equal(detail.strict, sem && diag);
  }
}
assert.equal(summary.allGNU.semantic, semantic);
assert.equal(summary.allGNU.diagnostic, diagnostic);
assert.equal(summary.allGNU.strict, strict);
assert.equal(summary.replayExitCode, 1);
assert.equal(summary.productAcceptance, false);
const controls = load(join(base, 'evidence/final/controls.json'));
assert.equal(controls.cases.length, 73);
assert.equal(controls.cases.filter(entry => entry.status === 'PASS').length, summary.controls.pass);
assert.equal(controls.workflows.length, 7);
assert.equal(controls.workflows.filter(entry => entry.status === 'PASS').length, 6);
assert.equal(controls.regexObservations.length, 6);
assert(controls.regexObservations.every(entry => entry.status === 'NOT READY'));
assert.equal(controls.fullFrozenControlsAccepted, false);
assert.deepEqual(controls.unhandledRejections, []);
const preliminary = gunzipSync(Buffer.from(readFileSync(join(base, 'evidence/attempt-01/provenance.json.gz.base64'), 'utf8'), 'base64'));
const encoding = load(join(base, 'evidence/attempt-01/encoding.json'));
assert.equal(sha256(preliminary), encoding.originalSha256);
assert.equal(preliminary.length, encoding.originalBytes);
const cleanup = load(join(base, 'CLEANUP.json'));
assert(cleanup.temporaryDirectories.every(entry => entry.removed && entry.checkedAbsent));
const comparator = spawnSync(process.execPath, ['--input-type=module', '-', 'compare', join(base, 'evidence/final/candidate-report.json')], { cwd: root, input: git(['show', `${freezeCommit}:${frozenPath}/runner.mjs.data`]), timeout: 10000, maxBuffer: 1024 * 1024 });
assert.equal(comparator.status, 1, 'must retain frozen mismatch exit, not treat as candidate success');
assert.equal(comparator.stderr.toString(), '');
assert.deepEqual(snapshot(base).filter(entry => !entry.directory && entry.path !== 'MANIFEST.json'), manifest.files);
assert.deepEqual(snapshot(frozen), provenance.frozenManifest);
console.log(JSON.stringify({ integrity: 'PASS', originalGNU: { denominator: 104, semantic, diagnostic, strict }, independentNonregex: summary.nonregex, candidateReplayExit: 1, regexSafety: 'NOT READY', writesCommittedEvidence: false, checksAppendedFiles: true, productAcceptance: false }, null, 2));
