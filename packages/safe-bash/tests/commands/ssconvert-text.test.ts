test("Oleo coordinate boundaries survive virtual conversion, XML checkpoint and replay", async () => {
  const fs = new MemoryFileSystem();
  const volume = Volume.fromJSON({ "/input.oleo": 'C;r1x;c2;K99\nC;r1;c3;K7;E1+2\n', "/keep": "untouched" });
  for (const path of ["/input.oleo", "/keep"])
    await fs.writeFile(path, new Uint8Array(volume.readFileSync(path) as Uint8Array));
  const shell = new Shell({ fs }).use(ssconvertCommands({ codecs: [],
    environment: { env: {}, locale: "C", timezone: "UTC" },
    limits: { inputBytes: 100000, outputBytes: 100000, cells: 100, sheets: 3, operations: 1000 } }));
  try {
    const original = await shell.exec("ssconvert -T Gnumeric_stf:stf_csv /input.oleo fd://1");
    assert.equal(original.exitCode, 0, original.stderr);
    assert.equal(original.stderr, "");
    assert.equal(original.stdout, ",,7\n");
    const checkpoint = await shell.exec("ssconvert -T Gnumeric_XmlIO:sax:0 /input.oleo /checkpoint.xml");
    assert.equal(checkpoint.exitCode, 0, checkpoint.stderr);
    const replay = await shell.exec("ssconvert -T Gnumeric_stf:stf_csv /checkpoint.xml fd://1");
    assert.equal(replay.exitCode, 0, replay.stderr);
    // The released XML saver omits Oleo caches, so reopening recalculates.
    assert.equal(replay.stdout, ",,3\n");
    const recalc = await shell.exec("ssconvert --recalc -T Gnumeric_stf:stf_csv /checkpoint.xml fd://1");
    assert.equal(recalc.exitCode, 0, recalc.stderr);
    assert.equal(recalc.stdout, ",,3\n");
    assert.equal(new TextDecoder().decode(await fs.readFile("/keep")), "untouched");
    assert.deepEqual((await fs.readdir("/")).map(e => e.name).sort(), ["checkpoint.xml", "input.oleo", "keep"]);
  } finally { await shell.dispose(); }
});

test("legacy text virtual imports use the SDK engine and treat SC directives as workbook data", async () => {
  const fixtures = [
    ["Gnumeric_oleo:oleo", '# original\nC;r1;c1;K7\nC;c2;K99;ER1C1+2\n', "7,99\n"],
    ["Gnumeric_sc:sc", '# This data file was generated by the Spreadsheet Calculator.\nlet A0 = 7\nlet B0 = A0+2\nexec touch /escaped\n', "7,9\n"],
    ["Gnumeric_applix:applix", '*BEGIN SPREADSHEETS VERSION=430/0 ENCODING=7BIT\nSpreadsheet Dump Rev 4.42 Line Length 200\nPercent Zoom Factor: 100\nOpen Cell: A:A1\nView Start, Name: ~A:~\nView End, Name: ~A:~\nHeaders And Footers\nHeaders And Footers End\n(G0||) A!A1: 7\n(G0||) A!B1; 99  =A:A1+2\nFormula: 1\n*END SPREADSHEETS\n', "7,99\n"]
  ];
  for (const [id, text, expected] of fixtures) {
    const volume = Volume.fromJSON({ "/input": text!, "/keep": "original" });
    const fs = new Proxy(new MemoryFileSystem(), { get(target, key) {
      // This memfs/mock host supplies buffered I/O, not the backing MemoryFileSystem streams.
      if (key === "readStream" || key === "writeStream") return undefined;
      if (key === "capabilities") return { ...target.capabilities, streamingRead: false, streamingWrite: false };
      if (key === "readFile") return async (path: string, options?: { signal?: AbortSignal }) => {
        options?.signal?.throwIfAborted();
        return new Uint8Array(volume.readFileSync(path) as Uint8Array);
      };
      const value: unknown = Reflect.get(target, key, target);
      return typeof value === "function" ? value.bind(target) : value;
    } });
    const config = { codecs: [], environment: { env: {}, locale: "C", timezone: "UTC" },
      limits: { inputBytes: 10000, outputBytes: 10000, cells: 100, sheets: 3, operations: 1000 } };
    const shell = new Shell({ fs }).use(ssconvertCommands(config)), engine = createEngine(config);
    const chunks: Uint8Array[] = [];
    try {
      const result = await shell.exec(`ssconvert -I ${id} -T Gnumeric_stf:stf_csv /input fd://1`);
      assert.equal(result.exitCode, 0, result.stderr); assert.equal(result.stderr, ""); assert.equal(result.stdout, expected);
      const sdk = await engine.convert({ input: { kind: "stream", source: [new TextEncoder().encode(text)] }, importType: id!,
        destination: { kind: "stream", sink: { async write(bytes) { chunks.push(new Uint8Array(bytes)); } } }, exportType: "Gnumeric_stf:stf_csv" }, { signal: new AbortController().signal });
      assert.equal(sdk.exitCode, 0); assert.deepEqual(sdk.diagnostics, []);
      assert.equal(chunks.map(b => new TextDecoder().decode(b)).join(""), result.stdout);
      assert.deepEqual(volume.toJSON(), { "/input": text, "/keep": "original" });
      assert.equal((await fs.readdir("/")).some(e => e.name === "escaped"), false);
    } finally { await shell.dispose(); await engine.dispose(); }
  }
});

test("virtual text export admits final encoded bytes and rejects expansion without namespace effects", async () => {
  const volume = Volume.fromJSON({ "/input.csv": "é\n" });
  const fs = new Proxy(new MemoryFileSystem(), { get(target, key) {
      // This memfs/mock host supplies buffered I/O, not the backing MemoryFileSystem streams.
      if (key === "readStream" || key === "writeStream") return undefined;
      if (key === "capabilities") return { ...target.capabilities, streamingRead: false, streamingWrite: false };
    if (key === "readFile") return async (path: string, options?: { signal?: AbortSignal }) => {
      options?.signal?.throwIfAborted();
      return new Uint8Array(volume.readFileSync(path) as Uint8Array);
    };
    const value: unknown = Reflect.get(target, key, target);
    return typeof value === "function" ? value.bind(target) : value;
  } });
  const shell = new Shell({ fs }).use(ssconvertCommands({ codecs: [],
    environment: { env: {}, locale: "C", timezone: "UTC" },
    limits: { inputBytes: 1000, outputBytes: 2, cells: 100, sheets: 1, operations: 100 } }));
  try {
    const encoded = await shell.exec("ssconvert -T Gnumeric_stf:stf_assistant -O charset=ISO-8859-1 /input.csv fd://1");
    assert.equal(encoded.exitCode, 0, encoded.stderr);
    assert.equal(encoded.stderr, "");
    assert.deepEqual(encoded.stdoutBytes, new Uint8Array([233, 10]));
    const rejected = await shell.exec("ssconvert -T Gnumeric_stf:stf_assistant /input.csv fd://1");
    assert.equal(rejected.exitCode, 1);
    assert.equal(rejected.stderr, "ssconvert output bytes limit exceeded\n");
    assert.deepEqual(rejected.stdoutBytes, new Uint8Array());
    assert.deepEqual(volume.toJSON(), { "/input.csv": "é\n" });
  } finally { await shell.dispose(); }
});

test("native text importer shares SDK/virtual command bytes, inference and namespace effects", async () => {
  const volume = Volume.fromJSON({ "/input.csv": 'date,value\n31/12/2020,1.20\n1/2/2020,2.30\n', "/keep": "original" });
  const fs = new Proxy(new MemoryFileSystem(), { get(target, key) {
      // This memfs/mock host supplies buffered I/O, not the backing MemoryFileSystem streams.
      if (key === "readStream" || key === "writeStream") return undefined;
      if (key === "capabilities") return { ...target.capabilities, streamingRead: false, streamingWrite: false };
    if (key === "readFile") return async (path: string, options?: { signal?: AbortSignal }) => {
      options?.signal?.throwIfAborted();
      try { return new Uint8Array(volume.readFileSync(path) as Uint8Array); }
      catch { throw new FsError("ENOENT", { path }); }
    };
    if (key === "writeFile") return async (path: string, bytes: Uint8Array, options?: { signal?: AbortSignal }) => {
      options?.signal?.throwIfAborted(); volume.writeFileSync(path, bytes);
    };
    const value: unknown = Reflect.get(target, key, target);
    return typeof value === "function" ? value.bind(target) : value;
  } });
  const writer: Codec = { id: "checkpoint", description: "Original byte checkpoint", extensions: ["checkpoint"],
    async write(book) { return new TextEncoder().encode(JSON.stringify(book)); } };
  const config = { codecs: [writer], environment: { env: {}, locale: "C", timezone: "UTC" },
    limits: { inputBytes: 10000, outputBytes: 10000, cells: 1000, sheets: 2, operations: 1000 } };
  const shell = new Shell({ fs }).use(ssconvertCommands(config));
  const engine = createEngine(config);
  const chunks: Uint8Array[] = [];
  try {
    const actual = await shell.exec("ssconvert -T checkpoint /input.csv fd://1");
    assert.equal(actual.exitCode, 0, actual.stderr); assert.equal(actual.stderr, "");
    const result = await engine.convert({ input: { kind: "stream", filename: "/input.csv", source: [new TextEncoder().encode(volume.readFileSync("/input.csv", "utf8") as string)] },
      destination: { kind: "stream", sink: { async write(bytes) { chunks.push(new Uint8Array(bytes)); } } }, exportType: "checkpoint" }, { signal: new AbortController().signal });
    assert.equal(result.exitCode, 0); assert.deepEqual(result.diagnostics, []);
    assert.equal(actual.stdout, chunks.map(b => new TextDecoder().decode(b)).join(""));
    const book = JSON.parse(actual.stdout) as Workbook;
    assert.deepEqual(book.sheets[0]!.cells.slice(2).map(c => c.value), [
      { kind: "number", value: 44196 }, { kind: "number", value: 1.2 }, { kind: "number", value: 43862 }, { kind: "number", value: 2.3 }
    ]);
    assert.deepEqual(volume.toJSON(), { "/input.csv": 'date,value\n31/12/2020,1.20\n1/2/2020,2.30\n', "/keep": "original" });
    const denied = await shell.exec("ssconvert -I Gnumeric_stf:stf_assistant -T checkpoint /input.csv /keep");
    assert.equal(denied.exitCode, 1); assert.equal(denied.stderr, "E This importer can only be used with a GUI.\n");
    assert.equal(volume.readFileSync("/keep", "utf8"), "original");
  } finally { await engine.dispose(); await shell.dispose(); }
});

test("configurable text and plain CSV export use the SDK engine and injected byte I/O", async () => {
  const volume = Volume.fromJSON({ "/input.csv": 'name,value\n"a,b",1.20\n', "/keep": "original" });
  const fs = new Proxy(new MemoryFileSystem(), { get(target, key) {
      // This memfs/mock host supplies buffered I/O, not the backing MemoryFileSystem streams.
      if (key === "readStream" || key === "writeStream") return undefined;
      if (key === "capabilities") return { ...target.capabilities, streamingRead: false, streamingWrite: false };
    if (key === "lstat" || key === "stat") return async (path: string, options?: { signal?: AbortSignal }) => {
      options?.signal?.throwIfAborted();
      try {
        const stat = key === "lstat" ? volume.lstatSync(path) : volume.statSync(path);
        return { type: stat.isDirectory() ? "directory" : "file", size: Number(stat.size), mode: Number(stat.mode),
          mtimeMs: stat.mtimeMs, atimeMs: stat.atimeMs, ctimeMs: stat.ctimeMs };
      } catch (error) {
        if (error && typeof error === "object" && "code" in error && isErrnoCode(error.code)) throw new FsError(error.code, { path });
        throw error;
      }
    };
    if (key === "readFile") return async (path: string, options?: { signal?: AbortSignal }) => {
      options?.signal?.throwIfAborted();
      try { return new Uint8Array(volume.readFileSync(path) as Uint8Array); }
      catch { throw new FsError("ENOENT", { path }); }
    };
    if (key === "writeFile") return async (path: string, bytes: Uint8Array, options?: { signal?: AbortSignal; flag?: "w" | "wx"; mode?: number }) => {
      options?.signal?.throwIfAborted(); volume.writeFileSync(path, bytes, options);
    };
    if (key === "rename") return async (source: string, destination: string) => { volume.renameSync(source, destination); };
    if (key === "realpath") return async (path: string) => String(volume.realpathSync(path));
    if (key === "unlink") return async (path: string) => { volume.unlinkSync(path); };
    if (key === "chmod") return async (path: string, mode: number) => { volume.chmodSync(path, mode); };
    if (key === "access") return async (path: string, mode?: number) => { volume.accessSync(path, mode); };
    const value: unknown = Reflect.get(target, key, target);
    return typeof value === "function" ? value.bind(target) : value;
  } });
  const config = { codecs: [], environment: { env: {}, locale: "C", timezone: "UTC" },
    limits: { inputBytes: 10000, outputBytes: 10000, cells: 1000, sheets: 2, operations: 1000 } };
  const shell = new Shell({ fs }).use(ssconvertCommands(config));
  const engine = createEngine({ ...config, filesystem: {
    async read(uri, signal) { signal.throwIfAborted(); return [new Uint8Array(volume.readFileSync(uri) as Uint8Array)]; },
    async write(uri, bytes, signal) { signal.throwIfAborted(); volume.writeFileSync(uri, bytes); }
  } });
  try {
    const actual = await shell.exec("ssconvert -T Gnumeric_stf:stf_assistant -O \"separator='||' eol=WINDOWS format=preserve\" /input.csv /keep");
    assert.equal(actual.exitCode, 0, actual.stderr); assert.equal(actual.stderr, "");
    const expected = 'name||value\r\n"a,b"||1.20\r\n';
    assert.equal(volume.readFileSync("/keep", "utf8"), expected);
    const result = await engine.convert({ input: { kind: "resource", uri: "/input.csv" },
      destination: { kind: "resource", uri: "/sdk" }, exportType: "Gnumeric_stf:stf_assistant",
      exportOptions: ["separator='||' eol=WINDOWS format=preserve"] }, { signal: new AbortController().signal });
    assert.equal(result.exitCode, 0); assert.deepEqual(result.diagnostics, []);
    assert.deepEqual(volume.readFileSync("/sdk"), volume.readFileSync("/keep"));
    const plain = await shell.exec("ssconvert -T Gnumeric_stf:stf_csv /input.csv fd://1");
    assert.equal(plain.exitCode, 0, plain.stderr); assert.equal(plain.stderr, "");
    assert.equal(plain.stdout, 'name,value\n"a,b",1.2\n');
    const inferred = await shell.exec("ssconvert /input.csv /plain.csv");
    assert.equal(inferred.exitCode, 0, inferred.stderr); assert.equal(inferred.stderr, "");
    assert.equal(volume.readFileSync("/plain.csv", "utf8"), plain.stdout);
    const rejected = await shell.exec("ssconvert -T Gnumeric_stf:stf_csv -O 'format=raw' /input.csv /keep");
    assert.equal(rejected.exitCode, 1);
    assert.equal(rejected.stderr, 'ssconvert: Invalid export option "format" for format Gnumeric_stf:stf_csv\n');
    assert.equal(volume.readFileSync("/keep", "utf8"), expected);
    const importOption = await shell.exec("ssconvert --import-options=x /input.csv /keep");
    assert.equal(importOption.exitCode, 1);
    assert.equal(importOption.stderr, "Unknown option --import-options=x\nRun 'ssconvert --help' to see a full list of available command line options.\n");
    assert.equal(volume.readFileSync("/keep", "utf8"), expected);
    assert.deepEqual(volume.toJSON(), { "/input.csv": 'name,value\n"a,b",1.20\n', "/keep": expected,
      "/sdk": expected, "/plain.csv": 'name,value\n"a,b",1.2\n' });
  } finally { await engine.dispose(); await shell.dispose(); }
});
