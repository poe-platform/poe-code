import fs from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const home=path.dirname(fileURLToPath(import.meta.url));
const inv=JSON.parse(fs.readFileSync(home+'/m01-INVENTORY.json'));
const rows=JSON.parse(gunzipSync(Buffer.from(fs.readFileSync(home+'/m02-INPUTS.json.gz.base64','utf8').trim(),'base64'),{maxOutputLength:4194304}));
const get=name=>Buffer.from(rows.find(row=>row.oid===inv.find(item=>item.path.endsWith('/'+name)).oid).body,'base64');
const seal=JSON.parse(get('PRESEAL.json'));
const prefix='tests/compatibility/bash-surface-independent-20260829/functional-reference-v3/';
const source=seal.files.filter(row=>row.role==='source-commit').map(row=>seal.sourceCommit+':'+prefix+row.path);
if(source.length!==21)throw Error('source count');
const review=JSON.parse(fs.readFileSync(home+'/m03-INVENTORY.json'));
const selected=review.filter(row=>row.path.endsWith('/v3/SCOPED-RECEIPT.json')||(row.path.includes('/v3/activation-v1/')&&/\/(RESULT|REPORT|PLACEHOLDER-HISTORY|PUBLICATION-TRANSPORT)\.(json|md)$/u.test(row.path)));
if(selected.length!==5||selected.some(row=>row.mode!=='100644'||row.bytes>65536))throw Error('review selection');
const version=JSON.parse(get('VERSION-PROVENANCE.json'));
console.log(JSON.stringify({version,selected,sourceCount:source.length}));
const specs=[...source,...selected.map(row=>row.oid),...version.files.map(row=>version.commit+':'+row.path)];
fs.writeFileSync(home+'/m04-SPECS.json',JSON.stringify(specs,null,2)+'\n',{flag:'wx'});
