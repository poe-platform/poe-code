import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { registerHooks, syncBuiltinESMExports } from 'node:module';
import childProcess from 'node:child_process';
import workerThreads from 'node:worker_threads';
import net from 'node:net';
import http from 'node:http';
import https from 'node:https';
import tls from 'node:tls';
import dgram from 'node:dgram';
const admission = JSON.parse(fs.readFileSync(process.env.SURFACE_ADMISSION));
const log = process.env.SURFACE_LOAD_LOG;
let written = 0;
const record = row => { const bytes = Buffer.from(JSON.stringify(row) + '\n'); written += bytes.length; if (written > 1048576) throw Error('LOAD_CAPTURE_STOP'); fs.appendFileSync(log, bytes); };
const deny = role => () => { record({ event: 'FORBIDDEN_RUNTIME_CAPABILITY', role }); throw Error('SURFACE_CAPABILITY_REFUSED:' + role); };
for (const name of ['spawn', 'spawnSync', 'exec', 'execSync', 'execFile', 'execFileSync', 'fork']) childProcess[name] = deny('child_process.' + name);
workerThreads.Worker = deny('Worker');
for (const [module, names] of [[net, ['connect', 'createConnection', 'createServer']], [http, ['request', 'get', 'createServer']], [https, ['request', 'get', 'createServer']], [tls, ['connect', 'createServer']], [dgram, ['createSocket']]]) for (const name of names) module[name] = deny('network.' + name);
globalThis.fetch = deny('fetch'); process.dlopen = deny('dlopen'); syncBuiltinESMExports();
registerHooks({ load(url, context, next) {
  if (url.startsWith('node:')) return next(url, context);
  if (!url.startsWith('file:')) throw Error('IMPORT_SCHEME_REFUSED');
  const parsed = new URL(url); if (parsed.search || parsed.hash) throw Error('IMPORT_SUFFIX_REFUSED');
  const filename = fileURLToPath(parsed), expected = admission.files[filename];
  if (!expected || !filename.endsWith('.mjs') && !filename.endsWith('.js') || fs.realpathSync(filename) !== filename) throw Error('IMPORT_PATH_REFUSED:' + filename);
  const loaded = next(url, context); const bytes = Buffer.from(loaded.source);
  const digest = createHash('sha256').update(bytes).digest('hex'); if (digest !== expected.sha256) throw Error('IMPORT_HASH_REFUSED');
  record({ event: 'load', filename, sha256: digest, role: expected.role }); return loaded;
} });
