import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";

const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const manifest = JSON.parse(readFileSync(new URL("data/MANIFEST.json", import.meta.url)));
const payload = gunzipSync(Buffer.from(readFileSync(new URL("data/EVIDENCE.json.gz.base64", import.meta.url), "utf8").replace(/\s/gu, ""), "base64"));
assert.equal(sha256(payload), manifest.payloadSha256);
const files = JSON.parse(payload);
assert.deepEqual(files.map(file => ({ path: file.path, bytes: Buffer.byteLength(file.text), sha256: sha256(Buffer.from(file.text)) })), manifest.files);
assert.equal(new Set(files.map(file => file.path)).size, files.length);
const reports = files.filter(file => file.path.endsWith("/REPORT.json")).map(file => ({ path: file.path, report: JSON.parse(file.text) }));
const completed = reports.filter(entry => entry.report.completed && entry.report.status === "author-scoped-pass");
assert.equal(completed.length, 1);
const { report } = completed[0];
assert.equal(report.status, "author-scoped-pass");
assert.deepEqual(report.failures, []);
assert.ok(report.controls.length > 60);
assert.ok(report.controls.every(entry => entry.status === "pass"));
assert.equal(report.originalInputsBefore.length, 14);
assert.deepEqual(report.originalInputsAfter, report.originalInputsBefore);
assert.deepEqual(report.sourceAfter, report.sourceBefore);
assert.deepEqual(report.package.after, report.package.before);
assert.equal(report.typecheck.builds, 1);
assert.equal(report.typecheck.status, "typecheck-passed-not-runtime-acceptance");
assert.equal(report.baselineDiagnostics.length, 14);
assert.equal(report.templateReplays.length, 2);
assert.ok(report.templateReplays.every(entry => entry.status === 0));
assert.equal(report.permission.supported, true);
assert.equal(report.node22Permission.supported, true);
for (const name of ["packed-du-runtime", "packed-du-runtime-node22", "canonical-config-fixture", "packed-du-types"]) assert.equal(report.commands.find(entry => entry.name === name)?.status, 0, name);
console.log(JSON.stringify({ evidenceFiles: files.length, candidate: report.candidate, controls: report.controls.length, strictGroups: report.typecheck.consumers.groups.length, preservedUnsuccessfulAttempts: reports.length - 1, scope: report.scope }));
