import assert from "node:assert/strict";
import vm from "node:vm";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { owned, repository, freeze, candidate, overlayCommit, frozenPath, overlayPath, manifestSha, hash, json, save, git, gitBytes, sort, record, committedTree, toolsSnapshot, identifiers, exactBytes } from "./common.mjs";

const phase = process.argv[2];
assert(["PRE", "POST"].includes(phase));
const tools = await toolsSnapshot();
await save(`${phase}-TOOLS.json`, tools);
for (const key of ["NODE_OPTIONS", "NODE_PATH", "TSX_TSCONFIG_PATH", "ESBUILD_BINARY_PATH"]) assert(!process.env[key], `unexpected ambient ${key}`);
const base = await committedTree(freeze, frozenPath);
const overlay = await committedTree(overlayCommit, overlayPath);
const oldEvidence = await committedTree("b3f45fa796282ef644729af36f9d41fc37693bd8", "tests/integration/du-v9-final-independent-20260827", false);
const oldV8 = await committedTree("ae0f8b3f4f927b06718fc51e176ca7a54b517364", frozenPath.replace("approved-v9", "approved-v8"));
const manifestBytes = gitBytes(freeze, `${frozenPath}/MANIFEST.json`);
assert.equal(hash(manifestBytes), manifestSha);
const manifest = JSON.parse(manifestBytes);
assert.deepEqual(sort([...manifest.files, record("MANIFEST.json", manifestBytes)]), base.records);
assert.equal(base.records.length, 23);
const delta = JSON.parse(gitBytes(overlayCommit, `${overlayPath}/manifest-delta.json`));
identifiers(delta.base.commit, delta.candidate.commit);
assert.deepEqual(sort([delta.changedFile.base, ...delta.untouchedFiles]), base.records);
assert.equal(delta.untouchedFiles.length, 22);
const patch = gitBytes(overlayCommit, `${overlayPath}/verify-v5.patch.data`);
exactBytes(patch, delta.patch, "patch");
const helper = await import(pathToFileURL(join(repository, overlayPath, "overlay.mjs")));
const baseHarness = gitBytes(freeze, `${frozenPath}/harness/verify-v5.mjs`);
const patched = helper.applyUnifiedPatch(baseHarness, patch);
exactBytes(patched, delta.changedFile.overlay, "patched harness");
const originalText = baseHarness.toString();
const patchedText = patched.toString();
const from = "async function seedLiteral(";
const through = "const summary = {";
const beforeCase = originalText.slice(originalText.indexOf(from), originalText.indexOf(through));
const afterCase = patchedText.slice(patchedText.indexOf(from), patchedText.indexOf("// V9_RECEIPT_AND_LINEAGE_ASSERTIONS_BEGIN"));
assert.equal(beforeCase, afterCase, "all case code, inputs, assertions and order must remain byte-identical");
const finalAssertions = originalText.split("\n").filter(line => line.startsWith("assert.equal(summary.byLineage"));
assert.equal(finalAssertions.length, 3);
for (const line of finalAssertions) assert(patchedText.includes(line));
const beginMarker = "// V9_LINEAGE_OVERLAY_BEGIN";
const endMarker = "// V9_LINEAGE_OVERLAY_END";
const region = patchedText.slice(patchedText.indexOf(beginMarker) + beginMarker.length, patchedText.indexOf(endMarker));
const context = vm.createContext({ assert });
vm.runInContext(`${region}\nglobalThis.members = [...lineageByCaseId];`, context);
const members = JSON.parse(JSON.stringify(context.members));
const previousNames = (await readFile(join(owned, "../fresh-source.stderr.data"), "utf8")).split("\n").filter(line => line.startsWith("ok - ")).map(line => line.slice(5));
assert.equal(previousNames.length, 40);
const intended = previousNames.map((name, index) => [`V5-${String(index + 1).padStart(3, "0")}`, index === 23 || name.startsWith("real ") || name.startsWith("observer-only file read") ? "v5-observer-policy-control" : name.startsWith("consumer-registered pending cleanup") || name.startsWith("actual Shell lifecycle") ? "postfreeze-lifecycle-addition" : "historical-frozen-derived"]);
assert.deepEqual(members.sort(), intended.sort());
const selected = gitBytes(freeze, `${frozenPath}/config/candidate-selected-paths.txt`).toString().trim().split("\n");
assert.equal(selected.length, 249);
assert.deepEqual(git(["ls-tree", "-r", "--name-only", candidate, "--", ...selected]).toString().trim().split("\n"), selected);
const candidateRecords = selected.map(path => record(path, gitBytes(candidate, path)));
const environment = JSON.parse(gitBytes(freeze, `${frozenPath}/fixtures/native-env-cases.json`));
assert.equal(environment.cases.length, 16);
const snapshot = { toolsSha256: hash(Buffer.from(json(tools))), base, overlay, oldEvidence, oldV8, candidate, candidateRecords, delta, environmentRows: 16, caseRegionSha256: hash(Buffer.from(beforeCase)), members, finalAssertions, explicitBinding: "pristine V9 manifest authenticates base only; overlay commit and manifest-delta authenticate patched harness" };
if (phase === "POST") assert.deepEqual(snapshot, JSON.parse(await readFile(join(owned, "PRE.json"))), "inputs or tools changed across replay");
await save(`${phase}.json`, snapshot);
await save(`${phase}-status.data`, git(["status", "--short"]));
await save(`${phase}-index.data`, git(["diff", "--cached", "--binary"]));
process.stdout.write(`${phase}: 23 pristine base files; 22 unchanged plus one authenticated patch; 31/2/7 membership and every case byte preserved; 249 candidate paths; 16 env rows.\n`);
