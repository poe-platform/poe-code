import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileHash, gitHash, inventory, owned, parse, recipe, repository, write } from "./recipe/authenticate.mjs";

const execution = join(owned, "execution-01");
const result = parse(join(execution, "RESULT.json"));
const producer = parse(join(execution, "PRODUCER.json"));
const settlement = parse(join(execution, "SETTLEMENT.json"));
const post = parse(join(execution, "POST.json"));
const manifest = parse(join(recipe, "MANIFEST.json"));
assert.equal(result.error, undefined);
assert.equal(result.transport.spawnCount, 1);
assert.equal(result.result.bytes, 1073872896);
assert.equal(result.result.sha256, "f5b4c8bf0f2f882ef51effdb305a5edf1c8c657d05ba2fd7594c679478fe668f");
assert.equal(result.diagnostic.thresholdBytes, 268435456);
assert.equal(result.diagnostic.operator, "<");
assert.equal(result.diagnostic.below256MiB, result.result.maxRssBytes < 268435456);
assert.equal(result.diagnostic.acceptanceRun, false);
for (const bytes of [producer.metrics.bytes, result.consumer.bytes, result.transport.producerReadBytes, JSON.parse(result.result.process.stderr).emitted]) assert.equal(bytes, result.result.bytes);
assert.equal(result.result.chunks, result.consumer.chunks);
assert.equal(producer.metrics.drains, JSON.parse(result.result.process.stderr).drains);
assert.equal(producer.metrics.falseWrites, producer.metrics.drains);
assert.equal(producer.pid, result.transport.pid);
assert.equal(producer.ppid, result.pid);
assert.equal(settlement.pid, result.pid);
assert.deepEqual(result.execArgv, ["--max-old-space-size=96"]);
assert.equal(producer.execArgv[0], "--max-old-space-size=96");
assert.equal(result.consumer.pending, 0);
assert.equal(result.transport.iteratorPendingAtEnd, 0);
assert.equal(producer.metrics.pendingDrainAtEnd, 0);
assert.equal(producer.metrics.writableLengthAtEnd, 0);
assert.equal(result.transport.readableLengthAtClose, 0);
assert.equal(result.transport.closeObserved, true);
assert.equal(settlement.closeObserved, true);
assert.equal(settlement.code, 0);
assert.equal(settlement.signal, null);
assert.deepEqual(settlement.signalsSent, []);
assert.deepEqual(settlement.remainingGroupMembers, []);
assert.equal(readFileSync(join(owned, "SUPERVISOR.exit.data"), "utf8").trim(), "0");
assert.equal(readFileSync(join(owned, "SUPERVISOR.stderr.data"), "utf8"), "");
for (const report of [result.memory, producer.memory]) for (const key of ["rss", "heapUsed", "heapTotal", "external", "arrayBuffers"]) {
  assert.ok(Number.isSafeInteger(report.peak[key]));
  for (const phase of report.phases) assert.ok(report.peak[key] >= phase[key]);
}
assert.deepEqual(inventory(recipe).sort(), [...Object.keys(manifest.files), "MANIFEST.json"].sort());
for (const filename of inventory(recipe)) assert.equal(await fileHash(join(recipe, filename)), await gitHash(post.recipeFreeze, relative(repository, join(recipe, filename))));
const initial = parse(join(owned, "AUTHENTICATION-INITIAL.json"));
for (const entry of initial.selected) assert.equal(await fileHash(join(repository, entry.path)), entry.sha256);
write(join(owned, "VALIDATION.json"), { at: new Date().toISOString(), verifierSha256: await fileHash(join(owned, "verify-results.mjs")), scope: "Read-only checks of existing single execution and selected frozen inputs; no diagnostic invocation, threshold pass assertion, product/cohort/archive execution", resultSha256: await fileHash(join(execution, "RESULT.json")), producerSha256: await fileHash(join(execution, "PRODUCER.json")), recipeFreeze: post.recipeFreeze, recipeFiles: inventory(recipe).length, selectedHistoricalFiles: initial.selected.length, allChecksCompleted: true, originalDisposition: "HOLD34/35", actual34: 0 });
