import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { archive, canonical, census, differences, fixture, review, run, save, sha256, treePaths } from './harness.mjs';

const revision = 'b494675c34dc289f4ad4b10a9201e1211eb0a7d8';
const directory = archive(revision, 'baseline-b494-retained');
const paths = treePaths(revision);
const before = census(directory, paths);
save('execution/baseline-tests-before.json', before);
const diagnostic = await run(directory, ['--import', 'tsx', '--input-type=module', '-e', 'const profile = await import("./tests/shell-stress/diagnostic-profiles/profile.ts"); profile.validateFrozenProfile();'], 'baseline-diagnostic-preflight');
const cleanup = await run(directory, ['--import', 'tsx', '--test', 'tests/shell/invocation-cleanup-public.test.ts'], 'baseline-cleanup-preflight');
const afterGuards = census(directory, paths);
assert.deepEqual(differences(before, afterGuards), []);
assert.equal(diagnostic.code, 1);
assert.match(diagnostic.stderr, /Frozen historical fixture\/helper changed: tests\/shell-stress\/differential.test.ts/);
assert.equal(cleanup.code, 1);
assert.match(cleanup.stdout, /# fail 10/);
const writer = await run(directory, ['--import', 'tsx', '--test', canonical], 'baseline-old-canonical');
const after = census(directory, paths);
save('execution/baseline-tests-after.json', after);
const changed = differences(before, after);
for (const row of changed) save(`execution/baseline-affected/${row.path}.data`, readFileSync(join(directory, row.path)));
assert.equal(writer.code, 0);
assert.match(writer.stdout, /# pass 2/);
assert.ok(changed.some(row => row.path === `${fixture}/artifacts/direct-registered-curl-buffer-307-replay.json`));
const rows = JSON.parse(readFileSync(join(review, 'frozen/99-diagnostics.json')));
const attributed = rows.map(row => {
  const path = row.detail.match(/(?:Frozen historical fixture\/helper changed|Live frozen source changed): ([^\n]+)/)?.[1];
  const expected = row.detail.match(/expected: '([a-f0-9]{64})'/)?.[1];
  const actual = row.detail.match(/actual: '([a-f0-9]{64})'/)?.[1];
  assert.ok(path && expected && actual);
  const cleanArchivedActual = sha256(readFileSync(join(directory, path)));
  assert.equal(cleanArchivedActual, actual);
  assert.notEqual(cleanArchivedActual, expected);
  assert.ok(!changed.some(change => change.path === path));
  return { id: row.id, name: row.name, group: row.group, path, expected, actual, cleanArchivedActual, matchesWriterChangedPath: false };
});
save('execution/attribution-99.json', { revision, beforeAnyWriter: true, diagnosticPreflight: { code: diagnostic.code, exactRefusal: true }, cleanupPreflight: { code: cleanup.code, failedHooks: 10 }, rows: attributed, conclusions: { exactRows: 99, diagnostic: 89, cleanup: 10, cleanMismatchProven: 99, writerChangedPathOverlap: 0, tapGuardFailuresCausedByWriter: 0, gateImmutabilityFailureCausedByWriter: true } });
save('execution/baseline-result.json', { revision, directory, archivedTests: paths.length, testsBeforeSha256: sha256(JSON.stringify(before)), testsAfterSha256: sha256(JSON.stringify(after)), changes: changed, writerPasses: 2, guardPreflightsBeforeWriter: true, retainedFailedCopy: true, retainedAffectedFiles: changed.map(row => `execution/baseline-affected/${row.path}.data`), noRestoreOrDeletion: true });
console.log(JSON.stringify({ directory, changed, attributed: attributed.length }, null, 2));
