import { FsError } from "../src/contracts/errors.js";
import { describe, expect, it } from "vitest";
import type { FileSystem } from "../src/contracts/filesystem.js";
import { readFileStream } from "../src/fs/read-file-stream.js";

function generated(size: number) {
  let position = 0, closes = 0, reads = 0, outstanding = 0, peak = 0;
  const buffer = new Uint8Array(4096);
  const fs = {
    capabilities: { retainedRead: true, streamingRead: false },
    readFile() { throw new Error("whole-file read"); },
    writeFile() { throw new Error("private spool"); },
    async openReadFile() {
      return {
        async read(offset: number, maximum: number) {
          expect(offset).toBe(position);
          expect(maximum).toBeLessThanOrEqual(buffer.length);
          expect(outstanding).toBe(0);
          reads++;
          const length = Math.min(maximum, size - position);
          for (let i = 0; i < length; i++) buffer[i] = (position + i) % 251;
          position += length; outstanding = length; peak = Math.max(peak, outstanding);
          return buffer.subarray(0, length);
        },
        async close() { closes++; buffer.fill(0); },
      };
    },
  } as unknown as FileSystem;
  return { fs, consumed() { outstanding = 0; }, state: () => ({ closes, reads, peak, position }) };
}

describe("bounded file stream", () => {
  for (const size of [4096, 4096 * 64, 4096 * 256]) it(`streams ${size} generated bytes without payload storage`, async () => {
    const storage = generated(size);
    let count = 0;
    for await (const bytes of readFileStream(storage.fs, "/input", { chunkSize: 4096 })) {
      await Promise.resolve(); // A sink must settle before the next storage read.
      let valid = true;
      for (const byte of bytes) if (byte !== count++ % 251) valid = false;
      expect(valid).toBe(true);
      storage.consumed();
    }
    expect(count).toBe(size);
    expect(storage.state().peak).toBeLessThanOrEqual(4096);
    expect(storage.state().closes).toBe(1);
  });
  it("closes on early return and cancellation without advancing storage", async () => {
    for (const cancel of [false, true]) {
      const storage = generated(65536), controller = new AbortController();
      const iterator = readFileStream(storage.fs, "/input", { chunkSize: 4096, signal: controller.signal });
      await iterator.next();
      if (cancel) {
        controller.abort(new Error("cancelled"));
        await expect(iterator.next()).rejects.toThrow("cancelled");
      } else await iterator.return(undefined);
      expect(storage.state()).toMatchObject({ closes: 1, reads: 1, position: 4096 });
    }
  });
  it("does not turn whole-file-only storage into a stream", async () => {
    const fs = { capabilities: { read: true }, readFile() { throw new Error("payload read"); } } as unknown as FileSystem;
    await expect(readFileStream(fs, "/input").next()).rejects.toMatchObject({ code: "ENOTSUP" });
  });
  it("honors path capabilities instead of global stream support", async () => {
    const storage = generated(4096);
    storage.fs.capabilitiesFor = async () => ({ streamingRead: false, retainedRead: true });
    storage.fs.readStream = () => { throw new Error("denied stream used"); };
    for await (const ignoredBytes of readFileStream(storage.fs, "/input", { chunkSize: 4096 })) storage.consumed();
    expect(storage.state().closes).toBe(1);
  });
  it("preserves read failure over cleanup failure", async () => {
    const fs = { capabilities: { retainedRead: true }, async openReadFile() { return {
      async read() { throw new Error("source failed"); }, async close() { throw new Error("close failed"); },
    }; } } as unknown as FileSystem;
    await expect(readFileStream(fs, "/input").next()).rejects.toThrow("source failed");
  });
});

it("retires a failing native iterator before trying retained ranges", async () => {
  const storage = generated(4096);
  let retired = 0;
  storage.fs.readStream = () => ({ [Symbol.asyncIterator]: () => ({
    async next() { throw new FsError("ENOTSUP"); },
    async return() { retired++; return { done: true, value: undefined }; },
  }) });
  Object.defineProperty(storage.fs, "capabilities", { value: { retainedRead: true, streamingRead: true } });
  for await (const ignoredChunk of readFileStream(storage.fs, "/input", { chunkSize: 4096 })) storage.consumed();
  expect(retired).toBe(1);
  expect(storage.state().closes).toBe(1);
});

it("never replays an emitted prefix after a native source failure", async () => {
  const storage = generated(4096);
  storage.fs.readStream = async function* () { yield Uint8Array.of(1); throw new FsError("ENOTSUP"); };
  Object.defineProperty(storage.fs, "capabilities", { value: { retainedRead: true, streamingRead: true } });
  const iterator = readFileStream(storage.fs, "/input");
  expect((await iterator.next()).value).toEqual(Uint8Array.of(1));
  await expect(iterator.next()).rejects.toMatchObject({ code: "ENOTSUP" });
  expect(storage.state().reads).toBe(0);
});

it("closes a retained handle acquired after cancellation", async () => {
  const controller = new AbortController();
  let close = 0;
  const fs = { capabilities: { retainedRead: true }, async openReadFile() {
    controller.abort(false);
    return { async close() { close++; }, async read() { throw new Error("cancelled read"); } };
  } } as unknown as FileSystem;
  await expect(readFileStream(fs, "/input", { signal: controller.signal }).next()).rejects.toBe(false);
  expect(close).toBe(1);
});

it("retained ranges preserve short reads, offsets, and exclusive end bounds", async () => {
  const requests: number[][] = [];
  const fs = { capabilities: { retainedRead: true }, async openReadFile() { return {
    async read(position: number, maximum: number) { requests.push([position, maximum]); return new Uint8Array(Math.min(2, maximum)).fill(position); },
    async close() {},
  }; } } as unknown as FileSystem;
  const output: number[] = [];
  for await (const bytes of readFileStream(fs, "/input", { start: 3, endExclusive: 8, chunkSize: 4 })) output.push(...bytes);
  expect(requests).toEqual([[3, 4], [5, 3], [7, 1]]);
  expect(output).toEqual([3, 3, 5, 5, 7]);
});
