import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {readCjkMapping} from "./cjk-mapping-data.js";

const url="https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/mappings_tw.h";
const sha256="5055cd95f8d4a80014d6f3b6650d578eb424d2f9dcc86c5e4f4252fd93cf991c";
const response=await fetch(url);
if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
const bytes=new Uint8Array(await response.arrayBuffer());
if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
const source=new TextDecoder("utf-8",{fatal:true}).decode(bytes);
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
const lines=(values:readonly number[])=>Array.from({length:Math.ceil(values.length/24)},(_,i)=>values.slice(i*24,i*24+24).join(",")).join(",\n");
let output=`/*\n${license}\n*/\n// Generated by scripts/generate-big5.ts from ${url}\n// SHA-256: ${sha256}\n`;
for(const [name,tables] of [["big5",["big5"]],["cp950",["big5","cp950ext"]]] as const){
  const decode=new Array<number>(128*256).fill(-1),encode=new Map<number,number>();
  // CP950 tries its extension first. Overlay both directions independently;
  // reverse decoding would choose the wrong spelling for duplicate mappings.
  for(const table of tables){
    for(const [pair,point] of readCjkMapping(source,`${table}_decmap`,"U")){
      if(pair<0x8000)throw Error("unexpected ASCII Big5 mapping");
      decode[pair-0x8000]=point;
    }
    for(const [point,pair] of readCjkMapping(source,`${table}_encmap`,"N")){
      if(point<128||pair<0x8000)throw Error("unexpected ASCII Big5 mapping");
      encode.set(point,pair);
    }
  }
  const entries=[...encode].sort(([a],[b])=>a-b).flat();
  output+=`export const ${name}Decode:readonly number[]=Object.freeze([\n${lines(decode)}\n]);\n`;
  output+=`export const ${name}Encode:readonly number[]=Object.freeze([\n${lines(entries)}\n]);\n`;
}
await writeFile(new URL("../src/runtime/big5-data.ts",import.meta.url),output);
console.log(`Generated Big5/CP950 mappings; SHA-256: ${createHash("sha256").update(output).digest("hex")}`);
