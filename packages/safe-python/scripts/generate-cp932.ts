import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {readCjkMapping} from "./cjk-mapping-data.js";

const url="https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/mappings_jp.h";
const sha256="09012ff9eb963073d42a8bce375c05484219537caa0cc2aa74baa63d5f3f1658";
const response=await fetch(url);
if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
const bytes=new Uint8Array(await response.arrayBuffer());
if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
const source=new TextDecoder("utf-8",{fatal:true}).decode(bytes);
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
let output=`/*\n${license}\n*/\n// Generated by scripts/generate-cp932.ts from ${url}\n// SHA-256: ${sha256}\n`;
for(const [name,sentinel] of [["jisx0208_decmap","U"],["jisxcommon_encmap","N"],["cp932ext_decmap","U"],["cp932ext_encmap","N"]]){
  const data=readCjkMapping(source,name,sentinel).flat();
  const lines=Array.from({length:Math.ceil(data.length/24)},(_,i)=>data.slice(i*24,i*24+24).join(",")).join(",\n");
  output+=`export const ${name}:readonly number[]=Object.freeze([\n${lines}\n]);\n`;
}
await writeFile(new URL("../src/runtime/cp932-data.ts",import.meta.url),output);
