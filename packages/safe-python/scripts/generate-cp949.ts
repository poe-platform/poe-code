import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {compileCp949Mappings} from "./cp949-data.js";

const url="https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/mappings_kr.h";
const sha256="334c6ed883d62725094114b1abd10c306d0810bbba8a055ea443bfef13147276";
const response=await fetch(url);
if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
const bytes=new Uint8Array(await response.arrayBuffer());
if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
const tables=compileCp949Mappings(new TextDecoder("utf-8",{fatal:true}).decode(bytes));
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
const lines=(values:number[])=>Array.from({length:Math.ceil(values.length/24)},(_,i)=>values.slice(i*24,i*24+24).join(",")).join(",\n");
await writeFile(new URL("../src/runtime/cp949-data.ts",import.meta.url),
  `/*\n${license}\n*/\n// Generated by scripts/generate-cp949.ts from ${url}\n// SHA-256: ${sha256}\n`+
  `export const cp949Decode:readonly number[]=Object.freeze([\n${lines(tables.decode)}\n]);\n`+
  `export const cp949Encode:readonly number[]=Object.freeze([\n${lines(tables.encode)}\n]);\n`);
console.log(`Generated ${tables.decode.filter(point=>point!==-1).length} decode and ${tables.encode.length/2} encode mappings.`);
