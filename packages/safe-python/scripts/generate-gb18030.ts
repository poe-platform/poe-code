import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {compileGb18030Mappings} from "./gb18030-data.js";

const url="https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/mappings_cn.h";
const sha256="5c75da57e7fcbb06106a64b03a7fc1f6e76fd9668306c66f71a6485e8eb550aa";
const response=await fetch(url);
if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
const bytes=new Uint8Array(await response.arrayBuffer());
if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
const tables=compileGb18030Mappings(new TextDecoder("utf-8",{fatal:true}).decode(bytes));
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
const lines=(values:number[])=>Array.from({length:Math.ceil(values.length/24)},(_,i)=>values.slice(i*24,i*24+24).join(",")).join(",\n");
let source=`/*\n${license}\n*/\n// Generated by scripts/generate-gb18030.ts from ${url}\n// SHA-256: ${sha256}\n`;
for(const [name,data] of [["gb18030ExtensionDecode",tables.decode],["gb18030ExtensionEncode",tables.encode],["gb18030BmpRanges",tables.ranges]] as const){
  source+=`export const ${name}:readonly number[]=Object.freeze([\n${lines(data)}\n]);\n`;
}
await writeFile(new URL("../src/runtime/gb18030-data.ts",import.meta.url),source);
console.log(`${tables.decode.filter(point=>point!==-1).length} decode, ${tables.encode.length/2} encode extensions, ${tables.ranges.length/3} BMP ranges.`);
