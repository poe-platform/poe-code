import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {compileGbkMappings} from "./gbk-data.js";

const url="https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/mappings_cn.h";
const sha256="5c75da57e7fcbb06106a64b03a7fc1f6e76fd9668306c66f71a6485e8eb550aa";
const response=await fetch(url);
if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
const bytes=new Uint8Array(await response.arrayBuffer());
if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
const tables=compileGbkMappings(new TextDecoder("utf-8",{fatal:true}).decode(bytes));
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
const lines=(values:number[])=>Array.from({length:Math.ceil(values.length/24)},(_,i)=>values.slice(i*24,i*24+24).join(",")).join(",\n");
await writeFile(new URL("../src/runtime/gbk-data.ts",import.meta.url),
  `/*\n${license}\n*/\n// Generated by scripts/generate-gbk.ts from ${url}\n// SHA-256: ${sha256}\n`+
  `export const gbkDecode:readonly number[]=Object.freeze([\n${lines(tables.decode)}\n]);\n`+
  `export const gbkEncode:readonly number[]=Object.freeze([\n${lines(tables.encode)}\n]);\n`);
console.log(`Generated ${tables.decode.filter(point=>point!==-1).length} decode and ${tables.encode.length/2} encode mappings.`);
