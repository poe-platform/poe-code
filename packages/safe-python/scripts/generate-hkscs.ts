import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {compileHkscsMappings} from "./hkscs-data.js";

const inputs=[
  ["mappings_tw.h","5055cd95f8d4a80014d6f3b6650d578eb424d2f9dcc86c5e4f4252fd93cf991c"],
  ["mappings_hk.h","80259d8dababbbacbc214158aebb1f17a53bbbfa2cac30da3ce0fe43435f344e"],
  ["_codecs_hk.c","2b1c4a0516cc930c58bf885baae06e7b7b676b5dc1713c0653bba1fc39c4e12d"]
] as const;
const sources=await Promise.all(inputs.map(async([name,digest])=>{
  const response=await fetch(`https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/${name}`);
  if(!response.ok)throw Error(`CPython download failed: ${response.status}`);
  const bytes=new Uint8Array(await response.arrayBuffer());
  if(createHash("sha256").update(bytes).digest("hex")!==digest)throw Error(`CPython hash mismatch: ${name}`);
  return new TextDecoder("utf-8",{fatal:true}).decode(bytes);
}));
const tables=compileHkscsMappings(sources[0],sources[1]);
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
const lines=(values:number[])=>Array.from({length:Math.ceil(values.length/24)},(_,i)=>values.slice(i*24,i*24+24).join(",")).join(",\n");
let output=`/*\n${license}\n*/\n// Generated by scripts/generate-hkscs.ts from CPython v3.14.7 Modules/cjkcodecs.\n`;
for(const [name,digest] of inputs)output+=`// ${name} SHA-256: ${digest}\n`;
for(const [name,values] of Object.entries(tables))output+=`export const hkscs${name[0].toUpperCase()+name.slice(1)}:readonly number[]=Object.freeze([\n${lines(values)}\n]);\n`;
await writeFile(new URL("../src/runtime/hkscs-data.ts",import.meta.url),output);
console.log(`${tables.decode.filter(point=>point!==-1).length} scalar decodings; ${tables.encode.length/2} singleton encodings; ${tables.expansions.length/3} expansions.`);
