import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {readCjkMapping} from "./cjk-mapping-data.js";
import {readJisPairs} from "./jisx0213-data.js";

const inputs=[
  ["mappings_jp.h","09012ff9eb963073d42a8bce375c05484219537caa0cc2aa74baa63d5f3f1658"],
  ["mappings_jisx0213_pair.h","b01e43c69e8edd8274ba9d6756357bea80a11507b125378927b37c7b443170e4"]
] as const;
const sources:string[]=[];
for(const [name,sha256] of inputs){
  const response=await fetch(`https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/${name}`);
  if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
  const bytes=new Uint8Array(await response.arrayBuffer());
  if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
  sources.push(new TextDecoder("utf-8",{fatal:true}).decode(bytes));
}
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
let output=`/*\n${license}\n*/\n// Generated by scripts/generate-jisx0213.ts from CPython v3.14.7.\n`;
for(const [name,sha256] of inputs)output+=`// ${name} SHA-256: ${sha256}\n`;
const tables=new Map<string,number[]>();
for(const name of ["jisx0213_1_bmp_decmap","jisx0213_2_bmp_decmap","jisx0213_1_emp_decmap","jisx0213_2_emp_decmap","jisx0213_bmp_encmap","jisx0213_emp_encmap"]){
  tables.set(name,readCjkMapping(sources[0],name,name.endsWith("encmap")?"N":"U",{M:-2}).flat());
}
tables.set("jisx0213_pair_decmap",readCjkMapping(sources[1],"jisx0213_pair_decmap","U",{},0xffffffff).flat());
tables.set("jisx0213_pair_encmap",readJisPairs(sources[1],46));
for(const [name,data] of tables){
  const lines=Array.from({length:Math.ceil(data.length/24)},(_,i)=>data.slice(i*24,i*24+24).join(",")).join(",\n");
  output+=`export const ${name}:readonly number[]=Object.freeze([\n${lines}\n]);\n`;
}
await writeFile(new URL("../src/runtime/jisx0213-data.ts",import.meta.url),output);
