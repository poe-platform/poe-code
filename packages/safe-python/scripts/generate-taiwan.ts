import {createHash} from "node:crypto";
import {readFile,writeFile} from "node:fs/promises";
import {compileTaiwanMappings} from "./taiwan-data.js";

const url="https://raw.githubusercontent.com/python/cpython/v3.14.7/Modules/cjkcodecs/mappings_tw.h";
const sha256="5055cd95f8d4a80014d6f3b6650d578eb424d2f9dcc86c5e4f4252fd93cf991c";
const response=await fetch(url);
if(!response.ok)throw Error(`CPython mapping download failed: ${response.status}`);
const bytes=new Uint8Array(await response.arrayBuffer());
if(createHash("sha256").update(bytes).digest("hex")!==sha256)throw Error("CPython mapping hash mismatch");
const tables=compileTaiwanMappings(new TextDecoder("utf-8",{fatal:true}).decode(bytes));
const license=await readFile(new URL("../CPYTHON-LICENSE.txt",import.meta.url),"utf8");
const lines=(values:number[])=>Array.from({length:Math.ceil(values.length/24)},(_,i)=>values.slice(i*24,i*24+24).join(",")).join(",\n");
let source=`/*\n${license}\n*/\n// Generated by scripts/generate-taiwan.ts from ${url}\n// SHA-256: ${sha256}\n`;
for(const name of ["big5","cp950"] as const){
  const table=tables[name];
  source+=`export const ${name}Decode:readonly number[]=Object.freeze([\n${lines(table.decode)}\n]);\n`;
  source+=`export const ${name}Encode:readonly number[]=Object.freeze([\n${lines(table.encode)}\n]);\n`;
  console.log(`${name}: ${table.decode.filter(point=>point!==-1).length} decode and ${table.encode.length/2} encode mappings.`);
}
await writeFile(new URL("../src/runtime/taiwan-data.ts",import.meta.url),source);
