import { capturedBesselSeries } from "./captured-bessel-series.js";
it.each([.0001, 69.00044772658632, 145.1722355890757])("preserves interruption identity during series work at order %s", order => {
  const reason = new Error("interrupted");
  let ticks = 0, caught: unknown;
  try {
    capturedBesselSeries(2.1663610121923824, order, true, {
      tick() { if (++ticks === 30) throw reason; }
    });
  } catch (error) { caught = error; }
  expect(caught).toBe(reason);
  expect(ticks).toBe(30);
});
