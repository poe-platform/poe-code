// Realm-private scratch: finite FMA never yields or calls host hooks, and each
// component copies its bits into bigint primitives before the next write.
const arithmeticBits = new DataView(new ArrayBuffer(8));

function components(value: number): { mantissa: bigint; exponent: number } {
  arithmeticBits.setFloat64(0, value); const bits = arithmeticBits.getBigUint64(0), exponent = Number(bits >> 52n & 2047n);
  const mantissa = (bits & ((1n << 52n) - 1n)) + (exponent ? 1n << 52n : 0n);
  return { mantissa: bits >> 63n ? -mantissa : mantissa, exponent: exponent ? exponent - 1075 : -1074 };
}

/** Correctly rounded binary64 FMA, including cancellation and subnormal ties.
 * Binary64 bounds every temporary integer to fewer than 4300 bits. */
export function fusedMultiplyAdd(a: number, b: number, addend: number): number {
  if (!Number.isFinite(a) || !Number.isFinite(b)) return a * b + addend;
  if (!Number.isFinite(addend)) return addend;
  if (a === 0 || b === 0) return a * b + addend;
  // Adding exact zero needs just one rounded product. Do not add the rounded
  // product to +0: that would erase negative zero produced by underflow.
  if (addend === 0) return a * b;
  const x = components(a), y = components(b), z = components(addend), productExponent = x.exponent + y.exponent;
  const exponent = Math.min(productExponent, z.exponent);
  const exact = (x.mantissa * y.mantissa << BigInt(productExponent - exponent)) + (z.mantissa << BigInt(z.exponent - exponent));
  if (exact === 0n) return a * b + addend;
  const magnitude = exact < 0n ? -exact : exact;
  const shift = Math.max(0, magnitude.toString(2).length - 53, -1074 - exponent);
  let significant = magnitude >> BigInt(shift);
  if (shift) {
    const dropped = magnitude - (significant << BigInt(shift)), half = 1n << BigInt(shift - 1);
    if (dropped > half || dropped === half && significant % 2n === 1n) significant++;
  }
  return (exact < 0n ? -1 : 1) * Number(significant) * 2 ** (exponent + shift);
}

