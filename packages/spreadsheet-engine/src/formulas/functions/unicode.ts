export function isUnicodePrintable(code: number): boolean {
  let low = 0, high = excluded.length - 1;
  while (low <= high) {
    const middle = (low + high) >>> 1, [first, last] = excluded[middle]!;
    if (code < first) high = middle - 1;
    else if (code > last) low = middle + 1;
    else return false;
  }
  return code >= 0 && code <= 0x10ffff;
}
export function simpleUnicodeCase(code: number, uppercase: boolean): string {
  return String.fromCodePoint((uppercase ? upper : lower).get(code) ?? code);
}
