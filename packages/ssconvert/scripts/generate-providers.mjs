import { readdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../src/codecs/", import.meta.url);
const names = (await readdir(new URL("providers/", root))).filter((name) => name.endsWith(".ts")).sort();
const body = "// Generated by scripts/generate-providers.mjs; edit one provider file instead.\n" +
  names.map((name, index) => `import provider${index} from ${JSON.stringify(`./providers/${name.slice(0, -3)}.js`)};\n`).join("") +
  `export const sourceProviders = [${names.map((_, index) => `provider${index}`).join(", ")}] as const;\n`;
const target = new URL("providers.generated.ts", root);
const previous = await readFile(target, "utf8").catch((error) => {
  if (error.code !== "ENOENT") throw error;
  return "";
});
if (previous !== body) await writeFile(target, body);
