import { expect, it } from "vitest";
import { Volume } from "memfs";
import { createEngine } from "../engine.js";
import { readApplix } from "./applix.js";
import { parseExpression } from "../formulas/parser.js";
import { gnumericGrammar } from "../formulas/conventions.js";
import { serializeExpression } from "../formulas/serialization.js";

const limits = { inputBytes: 100000, outputBytes: 100000, cells: 100, sheets: 4, operations: 1000 };
const environment = { env: {}, locale: "C", timezone: "UTC" };
const operation = { signal: new AbortController().signal };
const context = { ...operation, limits, environment, own() {} };
function applixFixture(records: string, metadata = "") {
  return '*BEGIN SPREADSHEETS VERSION=430/0 ENCODING=7BIT\nSpreadsheet Dump Rev 4.42 Line Length 200\nPercent Zoom Factor: 100\nOpen Cell: A:A1\nView Start, Name: ~A:~\nView End, Name: ~A:~\n' + metadata + 'Headers And Footers\nHeaders And Footers End\n' + records + '*END SPREADSHEETS\n';
}

it.each([
  ["Gnumeric_oleo:oleo", "/book.oleo", '# original fixture\nC;r1;c1;K7\nC;c2;K99;ER1C1+2\n', "Sheet1", "=$A$1+2"],
  ["Gnumeric_sc:sc", "/book.sc", '# This data file was generated by the Spreadsheet Calculator.\nlet A0 = 7\nlet B0 = A0+2\n', "SC", "=A1+2"],
  ["Gnumeric_applix:applix", "/book.as", applixFixture('(G0||) A!A1: 7\n(G0||) A!B1; 99  =A:A1+2\nFormula: 1\n'), "A", "=A!A1+2"]
])("loads %s through the shared engine and injected byte filesystem", async (id, filename, text, name, formula) => {
  const volume = Volume.fromJSON({ [filename]: text, "/keep": "untouched" });
  const engine = createEngine({ codecs: [], limits, environment, filesystem: {
    async read(uri, signal) { signal.throwIfAborted(); return [new Uint8Array(volume.readFileSync(uri) as Uint8Array)]; },
    async write(uri, bytes, signal) { signal.throwIfAborted(); volume.writeFileSync(uri, bytes); }
  } });
  try {
    const book = await engine.readWorkbook({ kind: "resource", uri: filename }, { importType: id }, operation);
    expect(book.sheets[0]).toMatchObject({ name, cells: [
      { row: 0, column: 0, value: { kind: "number", value: 7 } },
      { row: 0, column: 1, formula }
    ] });
    const result = await engine.convert({ input: { kind: "resource", uri: filename }, importType: id,
      destination: { kind: "resource", uri: "/output.csv" }, exportType: "Gnumeric_stf:stf_csv", recalc: true }, operation);
    expect(result.exitCode).toBe(0);
    expect(volume.readFileSync("/output.csv", "utf8")).toBe("7,9\n");
    expect(volume.readFileSync("/keep", "utf8")).toBe("untouched");
    expect(engine.listServices("write").some(s => s.id === id)).toBe(false);
  } finally { await engine.dispose(); }
});

it("imports Applix named ranges, shared expressions, styles and renamed sheets", async () => {
  const text = applixFixture('(P2|B,FG1,TF0|T1FG1) A!A1: 0.5\n(G0||) A!B1; 2  =SUM(A:A1..A:A2)\nFormula: sum\n(G0||) A!B2. 3  shared sum\n', 'COLORMAP\nblack 0 0 0 0 0 0 \nred 0 0 255 255 0 0 \nEND COLORMAP\nTYPEFACE TABLE\nArial\nEND TYPEFACE TABLE\nSHEETS TABLE\nSheet A: ~Budget~\nEND SHEETS TABLE\nNamed Range, Name: .Amount. Coordinate: A:A1..A:A2\n');
  const book = await readApplix(new TextEncoder().encode(text), context);
  expect(book.names).toMatchObject([{ name: "Amount", expression: "=Budget!$A$1:$A$2" }]);
  expect(book.sheets[0]).toMatchObject({ name: "Budget", cells: [
    { row: 0, column: 0, format: "0.00%", style: { Fore: "FFFF0000", Font: { Bold: 1, Name: "Arial" } } },
    { row: 0, column: 1, formula: "=SUM(Budget!A1:A2)", cachedResult: { kind: "number", value: 2 } },
    { row: 1, column: 1, formula: "=SUM(Budget!A2:A3)", cachedResult: { kind: "number", value: 3 } }
  ] });
  expect(book.sheets[0]!.cells[0]!.style?.gnumeric).toMatchObject({ name: "Style", children: [
    { name: "Font", text: "Arial", attributes: expect.arrayContaining([{ name: "Bold", namespace: "", value: "1" }]) },
    { name: "StyleBorder", children: [{ name: "Top", attributes: expect.arrayContaining([{ name: "Color", namespace: "", value: "FFFF:0:0" }]) }] }
  ] });
});

it("preserves Applix native formula caches without an explicit recalculation", async () => {
  const book = await readApplix(new TextEncoder().encode(applixFixture('(G0||) A!A1; 99  =1+2\nFormula: x\n')), context);
  expect(book.sheets[0]!.cells[0]).toMatchObject({ cachedResult: { kind: "number", value: 99 }, formulaDirty: false });
});
it("rejects native-invalid Applix style syntax without publishing a workbook", async () => {
  await expect(readApplix(new TextEncoder().encode(applixFixture('(G0) A!A1: 7\n')), context)).rejects.toThrow("Invalid font specification");
});

it("imports Applix row attributes and relative names without expanding rows", async () => {
  const book = await readApplix(new TextEncoder().encode(applixFixture('(G0||) A!A1: 4\n',
    'Attr Table Start\n<ignored>\n<(F2||) >\nAttr Table End\nRow List A !1: 0-2:2 \nRelative Named Range, Name: .Next. tCol:1 tRow:2 tSheet:0 bCol:1 bRow:2 bSheet: 0 tColAbs:0 tRowAbs:0 tSheetAbs:1 bColAbs:0 bRowAbs:0 bSheetAbs:1\n')), context);
  expect(book.sheets[0]!.cells[0]).toMatchObject({ format: "General" });
  expect(book.sheets[0]!.unsupportedRecords).toMatchObject([{ kind: "Styles", disposition: "retained", data: { children: [{ name: "StyleRegion", children: [{ attributes: expect.arrayContaining([{ name: "Format", namespace: "", value: "0.00" }]) }] }] } }]);
  expect(book.names).toMatchObject([{ name: "Next", expression: "=B3", position: { row: 0, column: 0 } }]);
});

it("imports Applix array formulas and preserves member caches", async () => {
  const book = await readApplix(new TextEncoder().encode(applixFixture('(G0||) A!A1; 3  ~A:A1..A:A2~  =1+2\nFormula: array\n(G0||) A!A2: 4\n')), context);
  expect(book.sheets[0]!.formulaGroups).toMatchObject([{ kind: "array", range: { startRow: 0, endRow: 1, startColumn: 0, endColumn: 0 }, expression: "=1+2" }]);
  expect(book.sheets[0]!.cells).toMatchObject([
    { row: 0, column: 0, formula: "=1+2", cachedResult: { kind: "number", value: 3 } },
    { row: 1, column: 0, formula: "=1+2", cachedResult: { kind: "number", value: 4 } }
  ]);
});

it("roundtrips zero-based SC row references through the AST without changing axis ownership", () => {
  const grammar = { ...gnumericGrammar, rowBase: 0 as const };
  const parsed = parseExpression("=$A$0+B2", { grammar, position: { sheet: "SC", row: 2, column: 1 } });
  expect(parsed.ok).toBe(true);
  if (!parsed.ok) throw new Error(parsed.diagnostic.message);
  expect(serializeExpression(parsed.document, grammar, false, true)).toBe("=$A$0+B2");
  expect(serializeExpression(parsed.document, gnumericGrammar, false, true)).toBe("=$A$1+B3");
});

it("retains Applix default axes, initial view and row/column dimensions for document export", async () => {
  const text = applixFixture('(G0||) A!A1: 1\n').replace('View End, Name: ~A:~', 'View Top Left: A:B3\nView Open Cell: A:C4\nView Default Column Width 10\nView Default Row Height: 12\nView Row Heights: 2:32784\nView Column Widths: B:8\nView End, Name: ~A:~');
  const book = await readApplix(new TextEncoder().encode(text), context), s = book.sheets[0]!;
  expect(s.rows).toMatchObject([{ index: 1, sizePoints: 14.5 }]);
  expect(s.columns).toMatchObject([{ index: 1, sizePoints: 47.5 }]);
  expect(s.unsupportedRecords).toMatchObject([
    { kind: "Cols", data: { attributes: [{ name: "DefaultSizePts", namespace: "", value: "59" }] } },
    { kind: "Rows", data: { attributes: [{ name: "DefaultSizePts", namespace: "", value: "11.5" }] } },
    { kind: "Selections", data: { attributes: [{ name: "CursorCol", namespace: "", value: "2" }, { name: "CursorRow", namespace: "", value: "3" }] } },
    { kind: "SheetLayout", data: { attributes: [{ name: "TopLeft", namespace: "", value: "B3" }] } }
  ]);
});

it("imports Applix default precision markers, dates and literal apostrophes", async () => {
  const book = await readApplix(new TextEncoder().encode(applixFixture('(Ff||) A!A1: 1.5\n(D6||) A!A2: 2020-01-02\n(G0||) A!A3: \'literal\n')), context);
  expect(book.sheets[0]!.cells).toMatchObject([
    { format: "0.00", value: { kind: "number", value: 1.5 } },
    { format: "yyyy-mm-dd", value: { kind: "number", value: 43832 } },
    { value: { kind: "string", value: "'literal" } }
  ]);
});
