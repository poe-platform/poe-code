import { SsconvertError, type CapabilityContext } from "../contracts.js";
import type { AxisMetadata, Cell, ImportedValue, NamedExpression, UnsupportedRecord, Workbook } from "../workbook.js";
import { gnumericGrammar } from "../formulas/conventions.js";
import { recordInput } from "./record-text.js";
import { asciiDigit, asciiLetter, legacyCells, legacyCoordinate, legacyExpression, probeSignature } from "./legacy-records.js";
import { sylkStyleNode } from "./sylk-styles.js";

const grammar = { ...gnumericGrammar, id: "sc", rowBase: 0 as const, wholeAxisReferences: false,
  functionAliases: { AVG: "AVERAGE", DTR: "RADIANS", FABS: "ABS", COLS: "COLUMNS", POW: "POWER", PROD: "PRODUCT",
    RND: "ROUND", RTD: "DEGREES", STDDEV: "STDEV", STON: "INT", SUBSTR: "MID" } };

// This is the native character rewrite, including its treatment of @ inside strings.
function expressionSource(source: string): string {
  let infunc = false, result = "";
  for (const c of source) {
    if (infunc) {
      infunc = asciiLetter(c);
      if (!infunc && c !== "(") result += "()";
      result += c;
    } else if (c === "@") infunc = true;
    else result += c;
  }
  return result + (infunc ? "()" : "");
}

// sc_parse_format scans three adjacent %i conversions, not three complete tokens.
function formatIntegers(source: string): number[] {
  const values: number[] = [];
  let at = 0;
  while (values.length < 3) {
    while (source[at] !== undefined && " \t\r\n\v\f".includes(source[at]!)) at++;
    let sign = 1;
    if (source[at] === "-" || source[at] === "+") { if (source[at] === "-") sign = -1; at++; }
    let base = 10, value = 0, digits = 0;
    if (source[at] === "0") {
      base = 8;
      if (source[at + 1] === "x" || source[at + 1] === "X") { base = 16; at += 2; }
    }
    for (; at < source.length; at++) {
      const code = source[at]!.toLowerCase().charCodeAt(0);
      const digit = code >= 48 && code <= 57 ? code - 48 : code >= 97 && code <= 102 ? code - 87 : -1;
      if (digit < 0 || digit >= base) break;
      value = value * base + digit; digits++;
    }
    if (!digits || !Number.isSafeInteger(value)) break;
    values.push(sign * value);
  }
  return values;
}

export function probeSc(bytes: Uint8Array, context: CapabilityContext): boolean {
  return probeSignature(bytes, "# This data file was generated by the Spreadsheet Calculator.", context);
}

export async function readSc(bytes: Uint8Array, context: CapabilityContext): Promise<Workbook> {
  const input = recordInput(bytes, context, "SC"), out = legacyCells(context, "SC");
  const names: NamedExpression[] = [], columns = new Map<number, AxisMetadata>(), precision = new Map<number, number>();
  let size = { rows: 65536, columns: 256 }, fatal = false, mode: Workbook["calculationMode"], iteration: Workbook["iteration"];
  let view: Record<string, ImportedValue> = {};
  const warnings: string[] = [];
  const formats = ["#.&", "0.&E+00", "##0.&E+00", "[$-f8f2]m/d/yy", "[$-f800]dddd, mmmm dd, yyyy"];
  function coord(source: string) {
    const direct = legacyCoordinate(source, 0);
    if (direct) return direct;
    const name = names.find(n => n.name === source);
    if (!name) return undefined;
    const parsed = legacyExpression(name.expression, gnumericGrammar, { sheet: "SC", row: 0, column: 0 }, context);
    if (!parsed.ok || parsed.document.root.kind !== "reference") return undefined;
    const first = parsed.document.root.first;
    return first.row && first.column ? { row: first.row.value, column: first.column.value, end: source.length } : undefined;
  }
  function fetch(row: number, column: number): Cell | undefined {
    if (row >= 16777216 || column >= 16384) {
      warnings.push(`The cell in row ${row} and column ${column} is beyond Gnumeric's maximum sheet size.`); return undefined;
    }
    while (size.rows <= row) size = { ...size, rows: size.rows * 2 };
    while (size.columns <= column) size = { ...size, columns: size.columns * 2 };
    return out.cells.get(`${row}:${column}`) ?? { row, column, value: { kind: "blank" } };
  }
  function applyPrecision(format: string, column: number) {
    let result = "";
    for (let at = 0; at < format.length; at++) {
      if (format[at] === "&" && format[at - 1] !== "\\") {
        const p = precision.get(column);
        if (p === undefined || p === -1) warnings.push("Encountered precision-dependent format without set precision.");
        if ((p ?? 0) > context.limits.inputBytes) throw new SsconvertError("resource-limit", "ssconvert SC precision limit exceeded");
        result += "0".repeat(Math.max(0, p ?? 0));
      } else result += format[at];
    }
    return result;
  }
  for (let line; (line = await input.next()) !== undefined;) {
    line = line.trimEnd();
    if (!asciiLetter(line[0])) continue;
    let end = 0;
    while (asciiLetter(line[end]) || asciiDigit(line[end]) || line[end] === "_") end++;
    if (end === line.length) continue;
    const cmd = line.slice(0, end);
    let at = end; while (line[at] === " ") at++;
    let str = line.slice(at);
    if (["label", "leftstring", "rightstring", "let"].includes(cmd)) {
      const eq = str.indexOf(" = "), pos = eq < 0 ? undefined : coord(str.slice(0, eq));
      if (!pos || eq + 3 >= str.length) { warnings.push(`Cannot parse ${line}\n`); fatal = true; continue; }
      str = str.slice(eq + 3);
      // sc_parse_label rejects malformed strings before cell fetch can resize the sheet.
      if (cmd !== "let" && (!str.startsWith('"') || str.length < 2 || !str.endsWith('"'))) continue;
      const cell = fetch(pos.row, pos.column);
      if (!cell) continue;
      if (cmd !== "let") {
        let value = "";
        for (const c of str.slice(1, -1)) if (c !== "\\") value += c;
        const { formula: ignoredFormula, cachedResult: ignoredCache, formulaDirty: ignoredDirty, ...plain } = cell;
        out.put({ ...plain,
          value: { kind: "string", value }, ...(cmd === "label" ? {} : { style: { ...cell.style, HAlign: cmd === "leftstring" ? 2 : 4 } }) });
      } else {
        const parsed = legacyExpression(expressionSource(str), grammar, { sheet: "SC", row: pos.row, column: pos.column }, context);
        if (!parsed.ok) { out.put(cell); warnings.push(`Unable to parse cmd='${cmd}', str='${str}', col=${pos.column}, row=${pos.row}.`); continue; }
        const root = parsed.document.root;
        const { formula: ignoredFormula, cachedResult: ignoredCache, formulaDirty: ignoredDirty, ...plain } = cell;
        out.put(root.kind === "literal" && root.value.kind === "number" ?
          { ...plain, value: root.value } : { ...plain, formula: parsed.formula, formulaDirty: true });
      }
    } else if (cmd === "define") {
      if (!str.startsWith('"')) continue;
      let i = 1, name = "";
      while (i < str.length && str[i] !== '"') { if (str[i] === "\\") i++; name += str[i++] ?? ""; }
      if (str[i] !== '"') continue;
      const parsed = legacyExpression(expressionSource(str.slice(i + 1).trimStart()), grammar, { sheet: "SC", row: 0, column: 0 }, context);
      if (!parsed.ok) { warnings.push(`Unable to parse cmd='define', str='${str.slice(i + 1).trimStart()}'.`); continue; }
      if (names.length >= context.limits.operations) throw new SsconvertError("resource-limit", "ssconvert SC names limit exceeded");
      const old = names.findIndex(n => n.name === name);
      const entry = { name, expression: parsed.formula, sheet: "SC" };
      if (old < 0) names.push(entry); else names[old] = entry;
    } else if (cmd === "set") {
      for (const option of str.split(" ")) {
        if (option.startsWith("iterations=")) {
          const n = parseInt(option.slice(11), 10);
          if (n > 0) iteration = { enabled: true, maximum: n, tolerance: 0.001 };
        } else if (option.startsWith("autocalc")) mode = "automatic";
        else if (option.startsWith("!autocalc")) mode = "manual";
      }
    } else if (cmd === "goto") {
      const pos = coord(str);
      if (pos) view = { ...view, selection: { row: pos.row, column: pos.column } };
    } else if (cmd === "fmt") {
      const q = str.indexOf('"'), pos = q > 0 ? coord(str.slice(0, q - 1)) : undefined;
      const close = str.indexOf('"', q + 1);
      if (!pos || close < 0) continue;
      const cell = fetch(pos.row, pos.column);
      if (cell) out.put({ ...cell, format: applyPrecision(str.slice(q + 1, close), pos.column) });
    } else if (cmd === "format") {
      if (asciiDigit(str[0])) { warnings.push(`Ignoring column format definition: ${str}`); continue; }
      let i = 0; while (asciiLetter(str[i]) && i < 2) i++;
      const from = legacyCoordinate(str.slice(0, i) + "0", 0);
      let to = from;
      if (str[i] === ":") {
        const start = ++i; while (asciiLetter(str[i]) && i - start < 2) i++;
        to = legacyCoordinate(str.slice(start, i) + "0", 0);
      }
      const parts = formatIntegers(str.slice(i));
      if (!from || !to || parts.length !== 3 || parts.some(n => !Number.isFinite(n))) { warnings.push(`Unable to parse: format ${str}`); continue; }
      const [width, p, type] = parts as [number, number, number];
      if (width > 0) while (size.columns <= to.column) size = { ...size, columns: size.columns * 2 };
      if (p > context.limits.inputBytes) throw new SsconvertError("resource-limit", "ssconvert SC precision limit exceeded");
      if (!formats[type]) warnings.push(`Column format ${type} is undefined.`);
      for (let col = from.column; col <= to.column; col++) {
        context.signal.throwIfAborted(); precision.set(col, p);
        if (col >= size.columns) continue;
        const old = columns.get(col);
        // Frozen C/UTC Sans 10 profile: eight-pixel digit width, 18 pixels per 12.75-point row.
        columns.set(col, { index: col, ...old, ...(width > 0 ? { sizePoints: (width * 8 + 4) * 17 / 24 } : {}),
          ...(formats[type] ? { style: { Format: applyPrecision(formats[type]!, col) } } : {}) });
      }
    } else warnings.push(`Unhandled directive: '${cmd}'`);
  }
  if (fatal) throw new SsconvertError("io", `W On worksheet SC:\n${warnings.map(w => `  W ${w}`).join("\n")}`);
  const cells = out.finish().map(cell => {
    const style = { ...columns.get(cell.column)?.style, ...cell.style, ...(cell.format ? { Format: cell.format } : {}) };
    if (!Object.keys(style).length) return cell;
    return { ...cell, ...(typeof style.Format === "string" ? { format: style.Format } : {}), style: { ...style, gnumeric: sylkStyleNode(style) } };
  });
  function node(name: string, attributes: Record<string, ImportedValue>, children: ImportedValue[] = []): ImportedValue {
    return { name, namespace: "http://www.gnumeric.org/v10.dtd", text: "", children,
      attributes: Object.entries(attributes).map(([name, value]) => ({ name, namespace: "", value: String(value) })) };
  }
  const retained: UnsupportedRecord[] = [];
  const styleRegions = [...columns.values()].filter(c => c.style).map(c => node("StyleRegion",
    { startRow: 0, endRow: size.rows - 1, startCol: c.index, endCol: c.index }, [sylkStyleNode({ ...c.style })]));
  if (styleRegions.length) retained.push({ source: "Gnumeric_XmlIO:sax", kind: "Styles", disposition: "retained", data: node("Styles", {}, styleRegions) });
  const hardWidths = [...columns.values()].filter(c => c.sizePoints !== undefined).map(c => node("ColInfo", { No: c.index, HardSize: 1 }));
  if (hardWidths.length) retained.push({ source: "Gnumeric_XmlIO:sax", kind: "Cols", disposition: "retained", data: node("Cols", {}, hardWidths) });
  const selection = view.selection as { row: number; column: number } | undefined;
  if (selection) retained.push({ source: "Gnumeric_XmlIO:sax", kind: "Selections", disposition: "retained",
    data: node("Selections", { CursorCol: selection.column, CursorRow: selection.row },
      [node("Selection", { startCol: selection.column, startRow: selection.row, endCol: selection.column, endRow: selection.row })]) });
  return { sheets: [{ id: "SC", name: "SC", size, cells, columns: [...columns.values()], view,
    ...(retained.length ? { unsupportedRecords: retained } : {}) }], activeSheet: "SC", names,
    ...(mode ? { calculationMode: mode } : {}), ...(iteration ? { iteration } : {}) };
}
