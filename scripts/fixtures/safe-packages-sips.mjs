import assert from "node:assert/strict";
import { Shell } from "@poe-platform/safe-bash/core";
import { Shell as RootShell, createSipsCommand as createRootSipsCommand } from "@poe-platform/safe-bash";
import { sipsCommands, createSipsCommand, createIdentifyCommand } from "@poe-platform/safe-bash/commands/sips";
import { pandocCommands } from "@poe-platform/safe-bash/commands/pandoc";
import { shufCommands } from "@poe-platform/safe-bash/commands/shuf";
import sharp from "@poe-platform/safe-bash/sharp";
import { readHeifMetadataFromSource } from "@poe-platform/safe-bash/image-ast";
import { createMemoryFileSystem } from "@poe-platform/safe-fs";

export const verification = (async () => {
  assert.equal(RootShell, Shell);
  assert.equal(createRootSipsCommand().runtimeIdentity, createSipsCommand().runtimeIdentity);
  const heif = await sharp({create: {width: 3, height: 2, channels: 4, background: "blue"}}).heif().toBuffer();
  class BorrowedBytes extends Uint8Array {slice(start, end) {return this.subarray(start, end);}}
  const loan = new BorrowedBytes(4096);
  const metadata = await readHeifMetadataFromSource({size: heif.length, async read(position, length) {loan.fill(0);loan.set(heif.subarray(position, position + length));return loan.subarray(0, length);}}, new AbortController().signal);
  assert.equal(metadata.width, 3);
  assert.equal(metadata.height, 2);
  const fs = createMemoryFileSystem();
  await fs.writeFile("/in.png", await sharp({create: {width: 13, height: 7, channels: 4, background: "blue"}}).png().toBuffer());
  await fs.writeFile("/input.md", new TextEncoder().encode("alpha\n\nbeta\n"));
  await fs.writeFile("/random", new Uint8Array(128));
  const filesystem = new Proxy(fs, {get(target, key) {
    if (key === "readFile" || key === "writeFile") return () => {throw new Error("whole-file I/O forbidden");};
    const value = Reflect.get(target, key, target);
    return typeof value === "function" ? value.bind(target) : value;
  }});
  const shell = new Shell({fs: filesystem}).use(sipsCommands()).use(pandocCommands()).use(shufCommands()).use({name: "retained-identify", setup(host) {host.commands.register(createIdentifyCommand());}});
  try {
    const result = await shell.exec("sips -r 90 -s format jpeg /in.png --out /out.jpg && identify -format '%m %wx%h' /out.jpg");
    assert.equal(result.exitCode, 0, result.stderr);
    assert.ok(result.stdout.endsWith("JPEG 7x13"));
    assert.equal((await sharp(await fs.readFile("/out.jpg")).metadata()).width, 7);
    const pdf = await shell.exec("sips -s format pdf /out.jpg --out /out.pdf");
    assert.equal(pdf.exitCode, 0, pdf.stderr);
    assert.equal((await sharp(await fs.readFile("/out.pdf")).metadata()).width, 7);
    const pdfInput = await shell.exec("sips -s format png /out.pdf --out /pdf-sips.png && identify -verbose /out.pdf");
    assert.equal(pdfInput.exitCode, 0, pdfInput.stderr);
    assert.ok(pdfInput.stdout.includes("Entropy:"));
    assert.equal((await sharp(await fs.readFile("/pdf-sips.png")).metadata()).height, 13);
    const pdfFile = await sharp("/out.pdf", {filesystem}).resize(5, 9).png().toFile("/pdf-sdk.png");
    assert.equal(pdfFile.width, 5);
    assert.equal(pdfFile.height, 9);
    await fs.link("/out.jpg", "/hard.jpg");
    await fs.symlink("out.jpg", "/link.jpg");
    const aliased = await shell.exec("sips -r 90 /link.jpg /out.jpg /hard.jpg");
    assert.equal(aliased.exitCode, 0, aliased.stderr);
    assert.equal(await fs.readlink("/link.jpg"), "out.jpg");
    assert.equal((await sharp(await fs.readFile("/out.jpg")).metadata()).width, 13);
    assert.deepEqual(await fs.readFile("/hard.jpg"), await fs.readFile("/out.jpg"));
    const svg = new TextEncoder().encode('<svg width="9" height="5"><rect width="9" height="5" fill="red"/></svg>');
    const svgInfo = await sharp(svg, {filesystem}).toFile("/svg.png");
    assert.equal(svgInfo.format, "png");
    assert.equal((await sharp(await fs.readFile("/svg.png")).metadata()).width, 9);
    await fs.writeFile("/vector.svg", svg);
    const svgQuery = await shell.exec("sips -g pixelWidth /vector.svg");
    assert.equal(svgQuery.exitCode, 0, svgQuery.stderr);
    assert.ok(svgQuery.stdout.includes("pixelWidth: 9"));
    assert.equal((await sharp("/vector.svg", {filesystem}).metadata()).height, 5);
    const svgFile = await sharp("/vector.svg", {filesystem}).resize(6, 4).toFile("/vector.png");
    assert.equal(svgFile.format, "png");
    assert.equal(svgFile.width, 6);
    const svgConversion = await shell.exec("sips -s format png /vector.svg --out /vector-sips.png");
    assert.equal(svgConversion.exitCode, 0, svgConversion.stderr);
    const svgStats = await shell.exec("identify -verbose /vector.svg");
    assert.equal(svgStats.exitCode, 0, svgStats.stderr);
    const composed = await shell.exec("pandoc -f markdown -t plain /input.md | shuf --random-source=/random");
    assert.equal(composed.exitCode, 0, composed.stderr);
    assert.deepEqual(composed.stdout.split("\n").filter(Boolean).sort(), ["alpha", "beta"]);
    const inspected = await shell.exec("sips -g pixelWidth /out.jpg | shuf --random-source=/random");
    assert.equal(inspected.exitCode, 0, inspected.stderr);
    assert.ok(inspected.stdout.includes("pixelWidth: 13"));
  } finally {await shell.dispose();}
})();
