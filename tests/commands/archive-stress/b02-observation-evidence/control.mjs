import assert from "node:assert/strict";
import { readFileSync, realpathSync } from "node:fs";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";

const [root, profile] = process.argv.slice(2);
assert.equal(profile, "memory-intact-57a6148");
assert.equal(realpathSync(process.cwd()), realpathSync(root));
const path = `${root}/src/fs/memory/index.ts`;
assert.equal(createHash("sha256").update(readFileSync(path)).digest("hex"), "57a6148aec90c7a1db058e59bd2586e7c162c74498309e7173443096cb8906ad");
const { createMemoryFileSystem } = await import(pathToFileURL(path).href);
const fs = createMemoryFileSystem();
await fs.writeFile("/data", Buffer.from("old destination"));
const before = await fs.stat("/data");
const writeStream = fs.writeStream;
const publish = writeStream.bind(fs);
let publications = 0;
fs.writeStream = async (target, body, options) => { publications++; await publish(target, body, options); };
const exposed = await fs.stat("/data");
const { identityScope, ...unscoped } = before;
assert.equal(typeof identityScope, "symbol");
assert.deepEqual(exposed, unscoped);
assert.equal(exposed.identityScope, undefined);
fs.writeStream = writeStream;
const restored = await fs.stat("/data");
assert.deepEqual(restored, before);
assert.equal(publications, 0);
assert.equal(Buffer.from(await fs.readFile("/data")).toString(), "old destination");
console.log(JSON.stringify({ profile, noTarImportedOrInvoked: true, publications, beforeUnscoped: unscoped, exposed, sameScopeByReference: restored.identityScope === identityScope, fullStatEqualBeforeProofRead: true, bytesPreserved: true, interpretation: "same backing entry; instrumentation changed exposed identity eligibility before any archive operation" }));
